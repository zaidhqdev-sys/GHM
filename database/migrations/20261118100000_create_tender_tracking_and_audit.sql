-- ZAID Tender AI Phase 1, batch 2: tender tracking records and the append-only
-- tender audit event table. FEATURE-BRANCH MIGRATION. It must not be merged to
-- main or applied to any shared/production database while the production
-- migration reconciliation is unresolved. It is deliberately NOT in
-- src/db/production-pending-migration-allowlist.ts.
--
-- Access model: no application/runtime/migrator role gets any grant on these
-- tables. Every read and write goes through the ghm.gateway_*_tender_tracking
-- SECURITY DEFINER functions, each of which verifies a one-use signed Actor
-- Gateway assertion and checks active Business membership itself.

CREATE TABLE ghm.tender_tracking (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  title text NOT NULL,
  reference_number text,
  issuer_name text,
  -- User-supplied and therefore UNVERIFIED (owner decision Q2). https only.
  source_url text,
  closing_at timestamptz,
  stage text NOT NULL DEFAULT 'saved',
  created_by bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  updated_by bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  archived_at timestamptz,

  CONSTRAINT tender_tracking_title_valid
    CHECK (char_length(btrim(title)) BETWEEN 1 AND 300),
  CONSTRAINT tender_tracking_reference_valid
    CHECK (reference_number IS NULL OR char_length(btrim(reference_number)) BETWEEN 1 AND 120),
  CONSTRAINT tender_tracking_issuer_valid
    CHECK (issuer_name IS NULL OR char_length(btrim(issuer_name)) BETWEEN 1 AND 200),
  CONSTRAINT tender_tracking_source_url_valid
    CHECK (source_url IS NULL OR (
      char_length(source_url) BETWEEN 8 AND 500
      AND source_url ~* '^https://[^[:space:]]+$'
    )),
  CONSTRAINT tender_tracking_stage_valid
    CHECK (stage IN ('saved', 'evaluating', 'preparing', 'submitted', 'archived')),
  CONSTRAINT tender_tracking_archive_consistent
    CHECK ((stage = 'archived') = (archived_at IS NOT NULL))
);

CREATE INDEX tender_tracking_business_stage_idx
  ON ghm.tender_tracking (business_id, stage, id DESC);

-- Append-only evidence of successful tender writes. Denied attempts are NOT
-- recorded here (owner decision Q13: structured logs only); a raising function
-- would roll such a row back anyway.
CREATE TABLE ghm.tender_audit_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  -- Authoritative id generated by the Actor Gateway for this request.
  request_id uuid NOT NULL,
  -- Opaque, UNTRUSTED correlation id supplied by the caller (Tender AI). Never an
  -- identity or authorization input.
  client_correlation_id uuid,
  actor_account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  operation text NOT NULL,
  resource_type text NOT NULL,
  -- No foreign key: the event must outlive permanent deletion of the resource.
  resource_id bigint NOT NULL,
  outcome text NOT NULL DEFAULT 'success',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

  CONSTRAINT tender_audit_operation_valid
    CHECK (operation IN (
      'tender.tracking.create',
      'tender.tracking.update',
      'tender.tracking.archive',
      'tender.tracking.delete'
    )),
  CONSTRAINT tender_audit_resource_type_valid
    CHECK (resource_type IN ('tracking')),
  CONSTRAINT tender_audit_outcome_valid
    CHECK (outcome = 'success'),
  CONSTRAINT tender_audit_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object'),
  CONSTRAINT tender_audit_metadata_bounded
    CHECK (octet_length(metadata::text) <= 2048),
  CONSTRAINT tender_audit_resource_id_positive
    CHECK (resource_id > 0)
);

CREATE INDEX tender_audit_event_business_idx
  ON ghm.tender_audit_event (business_id, occurred_at DESC, id DESC);
CREATE INDEX tender_audit_event_resource_idx
  ON ghm.tender_audit_event (resource_type, resource_id, id);
CREATE INDEX tender_audit_event_request_idx
  ON ghm.tender_audit_event (request_id);

