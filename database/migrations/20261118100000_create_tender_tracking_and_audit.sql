-- Internal helper: verify the one-use Actor Gateway assertion for ONE tender
-- operation. Not executable by any application role; only the SECURITY DEFINER
-- functions below (same owner) call it.
CREATE OR REPLACE FUNCTION ghm.verify_tender_gateway_assertion(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_operation text,
  p_context text,
  p_signature text
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $verify$
DECLARE
  v_secret bytea;
  v_expected bytea;
  v_provided bytea;
  v_payload text;
  v_diff integer := 0;
  v_i integer;
BEGIN
  IF session_user <> 'ghm_actor_gateway'
     OR p_actor IS NULL OR p_actor <= 0
     OR p_issued IS NULL OR p_nonce IS NULL
     OR p_operation IS NULL
     OR p_operation NOT IN (
       'tender.tracking.create', 'tender.tracking.list', 'tender.tracking.get',
       'tender.tracking.update', 'tender.tracking.archive', 'tender.tracking.delete'
     )
     OR p_context IS NULL
     OR octet_length(convert_to(p_context, 'UTF8')) > 32768
     OR p_signature IS NULL OR p_signature !~ '^[0-9a-f]{64}$' THEN
    RAISE EXCEPTION 'Invalid tender gateway assertion' USING ERRCODE = '42501';
  END IF;

  IF abs(extract(epoch FROM clock_timestamp())::bigint - p_issued) > 60 THEN
    RAISE EXCEPTION 'Tender gateway assertion expired' USING ERRCODE = '42501';
  END IF;

  SELECT secret INTO v_secret
    FROM ghm.actor_gateway_capability_assertion_secret
   WHERE singleton = true;
  IF v_secret IS NULL OR octet_length(v_secret) <> 32 THEN
    RAISE EXCEPTION 'Actor assertion verifier is not provisioned' USING ERRCODE = '42501';
  END IF;

  v_payload := 'ghm-actor-gateway:v2|' || p_actor::text || '|' || p_operation || '|' ||
               p_issued::text || '|' || p_nonce::text || '|' ||
               encode(convert_to(p_context, 'UTF8'), 'hex');
  v_expected := public.hmac(convert_to(v_payload, 'UTF8'), v_secret, 'sha256');
  v_provided := decode(p_signature, 'hex');
  FOR v_i IN 0..31 LOOP
    v_diff := v_diff | (get_byte(v_expected, v_i) # get_byte(v_provided, v_i));
  END LOOP;
  IF v_diff <> 0 THEN
    RAISE EXCEPTION 'Tender gateway assertion signature invalid' USING ERRCODE = '42501';
  END IF;

  IF NOT EXISTS (
    SELECT 1
      FROM ghm.account_identity ai
     WHERE ai.id = p_actor
       AND ai.account_status = 'active'
  ) THEN
    RAISE EXCEPTION 'Active GHM account required' USING ERRCODE = '42501';
  END IF;

  DELETE FROM ghm.actor_gateway_capability_assertion_nonce
   WHERE expires_at < clock_timestamp();
  BEGIN
    INSERT INTO ghm.actor_gateway_capability_assertion_nonce(nonce, expires_at)
    VALUES (
      p_nonce,
      GREATEST(clock_timestamp(), to_timestamp(p_issued)) + interval '60 seconds'
    );
  EXCEPTION WHEN unique_violation THEN
    RAISE EXCEPTION 'Tender gateway assertion replay detected' USING ERRCODE = '42501';
  END;
END;
$verify$;

-- Internal helper: the actor must hold an ACTIVE membership of the Business.
-- p_admin_only restricts to owner/administrator (archive and permanent delete).
-- Every failure is the same 42501 so a caller cannot tell "no such Business"
-- from "not your Business".
CREATE OR REPLACE FUNCTION ghm.require_tender_business_membership(
  p_actor bigint,
  p_business_id bigint,
  p_admin_only boolean
) RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $member$
BEGIN
  IF p_business_id IS NULL OR p_business_id <= 0 THEN
    RAISE EXCEPTION 'Invalid tender request' USING ERRCODE = '22023';
  END IF;
  PERFORM 1
    FROM ghm.business_membership m
   WHERE m.business_id = p_business_id
     AND m.account_id = p_actor
     AND m.membership_status = 'active'
     AND (
       (p_admin_only AND m.membership_role IN ('owner', 'administrator'))
       OR (NOT p_admin_only AND m.membership_role IN ('owner', 'administrator', 'member'))
     )
   FOR SHARE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Active Business membership with sufficient role required'
      USING ERRCODE = '42501';
  END IF;
END;
$member$;

