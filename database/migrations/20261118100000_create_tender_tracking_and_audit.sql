CREATE OR REPLACE FUNCTION ghm.gateway_create_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_title text,
  p_reference_number text,
  p_issuer_name text,
  p_source_url text,
  p_closing_at text,
  p_request_id uuid,
  p_client_correlation_id uuid
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $create$
DECLARE
  v_row ghm.tender_tracking;
  v_active integer;
  v_total integer;
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'title', p_title,
    'referenceNumber', p_reference_number,
    'issuerName', p_issuer_name,
    'sourceUrl', p_source_url,
    'closingAt', p_closing_at,
    'requestId', p_request_id::text,
    'clientCorrelationId', p_client_correlation_id::text
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.create', p_context, p_signature
  );
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, false);

  IF p_request_id IS NULL
     OR p_title IS NULL OR char_length(btrim(p_title)) NOT BETWEEN 1 AND 300
     OR (p_reference_number IS NOT NULL AND char_length(btrim(p_reference_number)) NOT BETWEEN 1 AND 120)
     OR (p_issuer_name IS NOT NULL AND char_length(btrim(p_issuer_name)) NOT BETWEEN 1 AND 200)
     OR (p_source_url IS NOT NULL AND (
          char_length(p_source_url) NOT BETWEEN 8 AND 500
          OR p_source_url !~* '^https://[^[:space:]]+$'))
     OR (p_closing_at IS NOT NULL
         AND p_closing_at !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,3})?Z$') THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  -- Serialise creates per Business so the caps cannot be raced past.
  PERFORM pg_advisory_xact_lock(hashtextextended('tender-tracking:' || p_business_id::text, 0));
  SELECT count(*) FILTER (WHERE t.stage <> 'archived'), count(*)
    INTO v_active, v_total
    FROM ghm.tender_tracking t
   WHERE t.business_id = p_business_id;
  IF v_active >= 500 OR v_total >= 2000 THEN
    RAISE EXCEPTION 'Tender tracking limit reached' USING ERRCODE = 'P0001';
  END IF;

  INSERT INTO ghm.tender_tracking (
    business_id, title, reference_number, issuer_name, source_url,
    closing_at, stage, created_by, updated_by
  ) VALUES (
    p_business_id, btrim(p_title), btrim(p_reference_number), btrim(p_issuer_name), p_source_url,
    p_closing_at::timestamptz, 'saved', p_actor, p_actor
  )
  RETURNING * INTO v_row;

  PERFORM ghm.record_tender_audit_event(
    p_request_id, p_client_correlation_id, p_actor, p_business_id,
    'tender.tracking.create', 'tracking', v_row.id,
    jsonb_build_object('stage', v_row.stage)
  );

  RETURN ghm.tender_tracking_json(v_row);
END;
$create$;

CREATE OR REPLACE FUNCTION ghm.gateway_list_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_stage text,
  p_limit integer,
  p_after bigint
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $list$
DECLARE
  v_items jsonb;
  v_last bigint;
  v_count integer;
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'stage', p_stage,
    'limit', p_limit,
    'after', p_after
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.list', p_context, p_signature
  );
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, false);

  IF p_limit IS NULL OR p_limit NOT BETWEEN 1 AND 50
     OR (p_after IS NOT NULL AND p_after <= 0)
     OR (p_stage IS NOT NULL AND p_stage NOT IN ('saved', 'evaluating', 'preparing', 'submitted', 'archived')) THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  -- Archived records are listed only when explicitly asked for.
  SELECT coalesce(jsonb_agg(ghm.tender_tracking_json(t.r) ORDER BY (t.r).id DESC), '[]'::jsonb),
         count(*),
         min((t.r).id)
    INTO v_items, v_count, v_last
    FROM (
      SELECT x AS r
        FROM ghm.tender_tracking x
       WHERE x.business_id = p_business_id
         AND (
           (p_stage IS NULL AND x.stage <> 'archived')
           OR x.stage = p_stage
         )
         AND (p_after IS NULL OR x.id < p_after)
       ORDER BY x.id DESC
       LIMIT p_limit
    ) t;

  RETURN jsonb_build_object(
    'items', v_items,
    'nextAfter', CASE WHEN v_count = p_limit THEN v_last ELSE NULL END
  );
END;
$list$;

CREATE OR REPLACE FUNCTION ghm.gateway_get_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_tracking_id bigint
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $get$
DECLARE
  v_row ghm.tender_tracking;
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'trackingId', p_tracking_id
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.get', p_context, p_signature
  );
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, false);

  IF p_tracking_id IS NULL OR p_tracking_id <= 0 THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row
    FROM ghm.tender_tracking t
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tender tracking record not found' USING ERRCODE = 'P0002';
  END IF;

  RETURN ghm.tender_tracking_json(v_row);
END;
$get$;

CREATE OR REPLACE FUNCTION ghm.gateway_update_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_tracking_id bigint,
  p_patch jsonb,
  p_request_id uuid,
  p_client_correlation_id uuid
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $update$
DECLARE
  v_row ghm.tender_tracking;
  v_before_stage text;
  v_keys text[];
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'trackingId', p_tracking_id,
    'patch', p_patch,
    'requestId', p_request_id::text,
    'clientCorrelationId', p_client_correlation_id::text
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.update', p_context, p_signature
  );
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, false);

  IF p_request_id IS NULL
     OR p_tracking_id IS NULL OR p_tracking_id <= 0
     OR p_patch IS NULL OR jsonb_typeof(p_patch) <> 'object' THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  SELECT array_agg(k ORDER BY k) INTO v_keys FROM jsonb_object_keys(p_patch) AS k;
  IF v_keys IS NULL
     OR EXISTS (
       SELECT 1 FROM unnest(v_keys) AS k
        WHERE k NOT IN ('title', 'referenceNumber', 'issuerName', 'sourceUrl', 'closingAt', 'stage')
     )
     -- title and stage can never be cleared; the others may be cleared with null.
     OR (p_patch ? 'title' AND (jsonb_typeof(p_patch->'title') <> 'string'
         OR char_length(btrim(p_patch->>'title')) NOT BETWEEN 1 AND 300))
     OR (p_patch ? 'referenceNumber' AND jsonb_typeof(p_patch->'referenceNumber') <> 'null'
         AND (jsonb_typeof(p_patch->'referenceNumber') <> 'string'
              OR char_length(btrim(p_patch->>'referenceNumber')) NOT BETWEEN 1 AND 120))
     OR (p_patch ? 'issuerName' AND jsonb_typeof(p_patch->'issuerName') <> 'null'
         AND (jsonb_typeof(p_patch->'issuerName') <> 'string'
              OR char_length(btrim(p_patch->>'issuerName')) NOT BETWEEN 1 AND 200))
     OR (p_patch ? 'sourceUrl' AND jsonb_typeof(p_patch->'sourceUrl') <> 'null'
         AND (jsonb_typeof(p_patch->'sourceUrl') <> 'string'
              OR char_length(p_patch->>'sourceUrl') NOT BETWEEN 8 AND 500
              OR (p_patch->>'sourceUrl') !~* '^https://[^[:space:]]+$'))
     OR (p_patch ? 'closingAt' AND jsonb_typeof(p_patch->'closingAt') <> 'null'
         AND (jsonb_typeof(p_patch->'closingAt') <> 'string'
              OR (p_patch->>'closingAt') !~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(\.[0-9]{1,3})?Z$'))
     -- 'archived' is reachable only through the separate archive operation.
     OR (p_patch ? 'stage' AND (jsonb_typeof(p_patch->'stage') <> 'string'
         OR (p_patch->>'stage') NOT IN ('saved', 'evaluating', 'preparing', 'submitted'))) THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row
    FROM ghm.tender_tracking t
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tender tracking record not found' USING ERRCODE = 'P0002';
  END IF;
  IF v_row.stage = 'archived' THEN
    RAISE EXCEPTION 'Archived tender tracking records cannot be edited' USING ERRCODE = 'P0001';
  END IF;
  v_before_stage := v_row.stage;

  UPDATE ghm.tender_tracking t
     SET title = CASE WHEN p_patch ? 'title' THEN btrim(p_patch->>'title') ELSE t.title END,
         reference_number = CASE WHEN p_patch ? 'referenceNumber'
                                 THEN btrim(p_patch->>'referenceNumber') ELSE t.reference_number END,
         issuer_name = CASE WHEN p_patch ? 'issuerName'
                            THEN btrim(p_patch->>'issuerName') ELSE t.issuer_name END,
         source_url = CASE WHEN p_patch ? 'sourceUrl' THEN p_patch->>'sourceUrl' ELSE t.source_url END,
         closing_at = CASE WHEN p_patch ? 'closingAt'
                           THEN (p_patch->>'closingAt')::timestamptz ELSE t.closing_at END,
         stage = CASE WHEN p_patch ? 'stage' THEN p_patch->>'stage' ELSE t.stage END,
         updated_by = p_actor,
         updated_at = now()
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id
  RETURNING * INTO v_row;

  -- Changed field NAMES and the stage transition only; never the values.
  PERFORM ghm.record_tender_audit_event(
    p_request_id, p_client_correlation_id, p_actor, p_business_id,
    'tender.tracking.update', 'tracking', v_row.id,
    jsonb_build_object(
      'fields', to_jsonb(v_keys),
      'fromStage', v_before_stage,
      'toStage', v_row.stage
    )
  );

  RETURN ghm.tender_tracking_json(v_row);
END;
$update$;

CREATE OR REPLACE FUNCTION ghm.gateway_archive_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_tracking_id bigint,
  p_request_id uuid,
  p_client_correlation_id uuid
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $archive$
DECLARE
  v_row ghm.tender_tracking;
  v_before_stage text;
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'trackingId', p_tracking_id,
    'requestId', p_request_id::text,
    'clientCorrelationId', p_client_correlation_id::text
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.archive', p_context, p_signature
  );
  -- Owner or administrator only.
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, true);

  IF p_request_id IS NULL OR p_tracking_id IS NULL OR p_tracking_id <= 0 THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_row
    FROM ghm.tender_tracking t
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id
   FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tender tracking record not found' USING ERRCODE = 'P0002';
  END IF;
  IF v_row.stage = 'archived' THEN
    RAISE EXCEPTION 'Tender tracking record is already archived' USING ERRCODE = 'P0001';
  END IF;
  v_before_stage := v_row.stage;

  UPDATE ghm.tender_tracking t
     SET stage = 'archived',
         archived_at = now(),
         updated_by = p_actor,
         updated_at = now()
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id
  RETURNING * INTO v_row;

  PERFORM ghm.record_tender_audit_event(
    p_request_id, p_client_correlation_id, p_actor, p_business_id,
    'tender.tracking.archive', 'tracking', v_row.id,
    jsonb_build_object('fromStage', v_before_stage)
  );

  RETURN ghm.tender_tracking_json(v_row);
END;
$archive$;

-- Permanent deletion is a separate, explicit operation with its own audit event
-- type. The audit event has no foreign key to the record, so it survives.
CREATE OR REPLACE FUNCTION ghm.gateway_delete_tender_tracking(
  p_actor bigint,
  p_issued bigint,
  p_nonce uuid,
  p_context text,
  p_signature text,
  p_business_id bigint,
  p_tracking_id bigint,
  p_request_id uuid,
  p_client_correlation_id uuid
) RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm, pg_temp
AS $delete$
DECLARE
  v_row ghm.tender_tracking;
BEGIN
  IF p_context::jsonb IS DISTINCT FROM jsonb_build_object(
    'businessId', p_business_id,
    'trackingId', p_tracking_id,
    'requestId', p_request_id::text,
    'clientCorrelationId', p_client_correlation_id::text
  ) THEN
    RAISE EXCEPTION 'Tender gateway assertion context mismatch' USING ERRCODE = '42501';
  END IF;

  PERFORM ghm.verify_tender_gateway_assertion(
    p_actor, p_issued, p_nonce, 'tender.tracking.delete', p_context, p_signature
  );
  PERFORM ghm.require_tender_business_membership(p_actor, p_business_id, true);

  IF p_request_id IS NULL OR p_tracking_id IS NULL OR p_tracking_id <= 0 THEN
    RAISE EXCEPTION 'Invalid tender tracking request' USING ERRCODE = '22023';
  END IF;

  DELETE FROM ghm.tender_tracking t
   WHERE t.id = p_tracking_id
     AND t.business_id = p_business_id
  RETURNING * INTO v_row;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Tender tracking record not found' USING ERRCODE = 'P0002';
  END IF;

  PERFORM ghm.record_tender_audit_event(
    p_request_id, p_client_correlation_id, p_actor, p_business_id,
    'tender.tracking.delete', 'tracking', v_row.id,
    jsonb_build_object('fromStage', v_row.stage, 'wasArchived', v_row.stage = 'archived')
  );

  RETURN jsonb_build_object('id', v_row.id, 'businessId', v_row.business_id, 'deleted', true);
END;
$delete$;

