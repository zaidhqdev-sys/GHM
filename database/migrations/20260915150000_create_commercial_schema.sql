    ON DELETE RESTRICT,
  provider_transaction_reference text,
  occurred_at timestamptz NOT NULL,
  recorded_at timestamptz NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

  CONSTRAINT commercial_payment_transaction_kind_valid
    CHECK (
      transaction_kind IN ('payment', 'refund', 'reversal', 'chargeback')
    ),

  CONSTRAINT commercial_payment_transaction_status_valid
    CHECK (
      transaction_status IN ('pending', 'succeeded', 'failed')
    ),

  CONSTRAINT commercial_payment_transaction_amount_valid
    CHECK (amount_minor_units > 0),

  CONSTRAINT commercial_payment_transaction_provider_reference_valid
    CHECK (
      provider_transaction_reference IS NULL
      OR length(provider_transaction_reference) BETWEEN 1 AND 200
    ),

  CONSTRAINT commercial_payment_transaction_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object')
);

