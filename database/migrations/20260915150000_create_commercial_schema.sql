CREATE TABLE ghm.commercial_trial (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,
  plan_version_id bigint NOT NULL
    REFERENCES ghm.commercial_plan_version(id)
    ON DELETE RESTRICT,
  activated_by bigint NOT NULL
    REFERENCES ghm.account_identity(id)
    ON DELETE RESTRICT,
  activated_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  lifecycle_status text NOT NULL DEFAULT 'active',
  ended_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_trial_expiry_valid
    CHECK (expires_at > activated_at),

  CONSTRAINT commercial_trial_lifecycle_valid
    CHECK (
      lifecycle_status IN ('active', 'expired', 'converted', 'cancelled')
    ),

  CONSTRAINT commercial_trial_active_ended_at_valid
    CHECK (
      (lifecycle_status = 'active' AND ended_at IS NULL)
      OR
      (lifecycle_status <> 'active' AND ended_at IS NOT NULL)
    ),

  CONSTRAINT commercial_trial_business_unique
    UNIQUE (business_id)
);

CREATE TABLE ghm.commercial_subscription (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,
  plan_version_id bigint NOT NULL
    REFERENCES ghm.commercial_plan_version(id)
    ON DELETE RESTRICT,
  price_id bigint
    REFERENCES ghm.commercial_plan_price(id)
    ON DELETE RESTRICT,
  trial_id bigint UNIQUE
    REFERENCES ghm.commercial_trial(id)
    ON DELETE RESTRICT,
  lifecycle_status text NOT NULL,
  current_period_start timestamptz,
  current_period_end timestamptz,
  cancel_at_period_end boolean NOT NULL DEFAULT false,
  cancelled_at timestamptz,
  founding_sequence integer,
  founding_protected_until timestamptz,
  provider_reference text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_subscription_lifecycle_valid
    CHECK (
      lifecycle_status IN (
        'trialing',
        'active',
        'past_due',
        'grace_period',
        'cancel_at_period_end',
        'cancelled',
        'expired',
        'suspended'
      )
    ),

  CONSTRAINT commercial_subscription_period_valid
    CHECK (
      current_period_end IS NULL
      OR (
        current_period_start IS NOT NULL
        AND current_period_end > current_period_start
      )
    ),

  CONSTRAINT commercial_subscription_founding_sequence_valid
    CHECK (
      founding_sequence IS NULL
      OR founding_sequence > 0
    ),

  CONSTRAINT commercial_subscription_cancellation_consistency
    CHECK (
      (
        cancel_at_period_end = true
        AND lifecycle_status = 'cancel_at_period_end'
      )
      OR
      (
        cancel_at_period_end = false
        AND lifecycle_status <> 'cancel_at_period_end'
      )
    ),

  CONSTRAINT commercial_subscription_provider_reference_valid
    CHECK (
      provider_reference IS NULL
      OR length(provider_reference) BETWEEN 1 AND 200
    )

);

CREATE UNIQUE INDEX commercial_subscription_current_business_uq
  ON ghm.commercial_subscription (business_id)
  WHERE lifecycle_status IN (
    'trialing',
    'active',
    'past_due',
    'grace_period',
    'cancel_at_period_end',
    'suspended'
  );

