CREATE TABLE ghm.commercial_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,
  subscription_id bigint
    REFERENCES ghm.commercial_subscription(id)
    ON DELETE RESTRICT,
