-- Commercial schema construction.
-- Contract:
-- docs/architecture/COMMERCIAL_MINIMUM_SCHEMA_CONTRACT.md
--
-- Provider-neutral commercial state for Business-scoped subscriptions,
-- trials, payments, provider events, commercial events, and founding
-- allocations.
--
-- No provider-specific schema.
-- No product-specific Supabase structures.
-- No production cutover authority.

CREATE TABLE ghm.commercial_plan (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  audience text NOT NULL DEFAULT 'business',
  lifecycle_status text NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_plan_code_valid
    CHECK (code = lower(code) AND code ~ '^[a-z][a-z0-9_]{2,49}$'),

  CONSTRAINT commercial_plan_name_valid
    CHECK (length(btrim(name)) BETWEEN 2 AND 100),

  CONSTRAINT commercial_plan_audience_valid
    CHECK (audience = 'business'),

  CONSTRAINT commercial_plan_lifecycle_valid
    CHECK (lifecycle_status IN ('draft', 'active', 'retired'))
);

CREATE TABLE ghm.commercial_plan_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_id bigint NOT NULL
    REFERENCES ghm.commercial_plan(id)
    ON DELETE RESTRICT,
  version integer NOT NULL,
  trial_days integer NOT NULL DEFAULT 0,
  founding_limit integer,
  founding_protection_months integer,
  effective_from timestamptz NOT NULL,
  effective_until timestamptz,
  lifecycle_status text NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_plan_version_version_valid
    CHECK (version >= 1),

  CONSTRAINT commercial_plan_version_trial_days_valid
    CHECK (trial_days BETWEEN 0 AND 30),

  CONSTRAINT commercial_plan_version_founding_limit_valid
    CHECK (founding_limit IS NULL OR founding_limit > 0),

  CONSTRAINT commercial_plan_version_founding_protection_valid
    CHECK (
      founding_protection_months IS NULL
      OR founding_protection_months BETWEEN 1 AND 60
    ),

  CONSTRAINT commercial_plan_version_effective_range_valid
    CHECK (
      effective_until IS NULL
      OR effective_until > effective_from
    ),

  CONSTRAINT commercial_plan_version_lifecycle_valid
    CHECK (lifecycle_status IN ('draft', 'active', 'retired')),

  CONSTRAINT commercial_plan_version_unique
    UNIQUE (plan_id, version)
);

CREATE TABLE ghm.commercial_plan_entitlement (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_version_id bigint NOT NULL
    REFERENCES ghm.commercial_plan_version(id)
    ON DELETE CASCADE,
  entitlement_code text NOT NULL,
  access_level text NOT NULL DEFAULT 'enabled',
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_plan_entitlement_code_valid
    CHECK (
      entitlement_code ~ '^[a-z][a-z0-9.]{2,99}$'
    ),

  CONSTRAINT commercial_plan_entitlement_access_level_valid
    CHECK (access_level = 'enabled'),

  CONSTRAINT commercial_plan_entitlement_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object'),

  CONSTRAINT commercial_plan_entitlement_unique
    UNIQUE (plan_version_id, entitlement_code)
);

CREATE TABLE ghm.commercial_plan_price (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plan_version_id bigint NOT NULL
    REFERENCES ghm.commercial_plan_version(id)
    ON DELETE RESTRICT,
  country_id bigint
    REFERENCES ghm.country(id)
    ON DELETE RESTRICT,
  currency_id bigint NOT NULL
    REFERENCES ghm.currency(id)
    ON DELETE RESTRICT,
  price_kind text NOT NULL,
  amount_minor_units bigint NOT NULL,
  billing_interval text NOT NULL DEFAULT 'month',
  effective_from timestamptz NOT NULL,
  effective_until timestamptz,
  lifecycle_status text NOT NULL DEFAULT 'draft',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_plan_price_kind_valid
    CHECK (price_kind IN ('founding', 'standard')),

  CONSTRAINT commercial_plan_price_amount_valid
    CHECK (amount_minor_units >= 0),

  CONSTRAINT commercial_plan_price_billing_interval_valid
    CHECK (billing_interval = 'month'),

  CONSTRAINT commercial_plan_price_effective_range_valid
    CHECK (
      effective_until IS NULL
      OR effective_until > effective_from
    ),

  CONSTRAINT commercial_plan_price_lifecycle_valid
    CHECK (lifecycle_status IN ('draft', 'active', 'retired'))
);

