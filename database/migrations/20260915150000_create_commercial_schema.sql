CREATE TABLE ghm.commercial_provider_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_code text NOT NULL,
  provider_event_id text NOT NULL,
  event_type text NOT NULL,
  payload_hash text NOT NULL,
  received_at timestamptz NOT NULL DEFAULT now(),
  occurred_at timestamptz,
  processing_status text NOT NULL DEFAULT 'received',
  processed_at timestamptz,
  failure_reason text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_provider_event_provider_code_valid
    CHECK (provider_code ~ '^[a-z][a-z0-9_]{1,49}$'),

  CONSTRAINT commercial_provider_event_id_valid
    CHECK (length(provider_event_id) BETWEEN 1 AND 200),

  CONSTRAINT commercial_provider_event_type_valid
    CHECK (length(event_type) BETWEEN 1 AND 100),

  CONSTRAINT commercial_provider_event_payload_hash_valid
    CHECK (payload_hash ~ '^[0-9a-f]{64}$'),

  CONSTRAINT commercial_provider_event_processing_status_valid
    CHECK (
      processing_status IN ('received', 'processed', 'ignored', 'failed')
    ),

  CONSTRAINT commercial_provider_event_processed_at_valid
    CHECK (
      (processing_status = 'received' AND processed_at IS NULL)
      OR
      (processing_status <> 'received' AND processed_at IS NOT NULL)
    ),

  CONSTRAINT commercial_provider_event_failure_reason_valid
    CHECK (
      failure_reason IS NULL
      OR length(failure_reason) BETWEEN 1 AND 1000
    ),

  CONSTRAINT commercial_provider_event_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object'),

  CONSTRAINT commercial_provider_event_identity_unique
    UNIQUE (provider_code, provider_event_id)
);

CREATE INDEX commercial_provider_event_processing_idx
  ON ghm.commercial_provider_event (
    processing_status,
    received_at
  );

CREATE TABLE ghm.commercial_payment_attempt (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,
  subscription_id bigint
    REFERENCES ghm.commercial_subscription(id)
    ON DELETE RESTRICT,
  price_id bigint NOT NULL
    REFERENCES ghm.commercial_plan_price(id)
    ON DELETE RESTRICT,
  initiated_by bigint NOT NULL
    REFERENCES ghm.account_identity(id)
    ON DELETE RESTRICT,
  attempt_status text NOT NULL DEFAULT 'pending_checkout',
  amount_minor_units bigint NOT NULL,
  currency_id bigint NOT NULL
    REFERENCES ghm.currency(id)
    ON DELETE RESTRICT,
  billing_interval text NOT NULL DEFAULT 'month',
  checkout_reference text,
  idempotency_key text NOT NULL UNIQUE,
  expires_at timestamptz,
  failure_code text,
  failure_message text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_payment_attempt_status_valid
    CHECK (
      attempt_status IN (
        'pending_checkout',
        'pending_payment',
        'succeeded',
        'failed',
        'expired',
        'cancelled'
      )
    ),

  CONSTRAINT commercial_payment_attempt_amount_valid
    CHECK (amount_minor_units > 0),

  CONSTRAINT commercial_payment_attempt_billing_interval_valid
    CHECK (billing_interval = 'month'),

  CONSTRAINT commercial_payment_attempt_idempotency_key_valid
    CHECK (length(idempotency_key) BETWEEN 8 AND 200),

  CONSTRAINT commercial_payment_attempt_checkout_reference_valid
    CHECK (
      checkout_reference IS NULL
      OR length(checkout_reference) BETWEEN 1 AND 200
    ),

  CONSTRAINT commercial_payment_attempt_failure_code_valid
    CHECK (
      failure_code IS NULL
      OR length(failure_code) BETWEEN 1 AND 100
    ),

  CONSTRAINT commercial_payment_attempt_failure_message_valid
    CHECK (
      failure_message IS NULL
      OR length(failure_message) BETWEEN 1 AND 1000
    ),

  CONSTRAINT commercial_payment_attempt_failed_reason_valid
    CHECK (
      attempt_status <> 'failed'
      OR failure_code IS NOT NULL
    )
);

CREATE INDEX commercial_payment_attempt_business_idx
  ON ghm.commercial_payment_attempt (business_id);

CREATE INDEX commercial_payment_attempt_subscription_idx
  ON ghm.commercial_payment_attempt (subscription_id);

CREATE INDEX commercial_payment_attempt_status_idx
  ON ghm.commercial_payment_attempt (
