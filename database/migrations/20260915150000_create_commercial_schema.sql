  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_event_type_valid
    CHECK (length(btrim(event_type)) BETWEEN 1 AND 100),

  CONSTRAINT commercial_event_source_valid
    CHECK (length(btrim(source)) BETWEEN 1 AND 100),

  CONSTRAINT commercial_event_idempotency_key_valid
    CHECK (
      idempotency_key IS NULL
      OR length(idempotency_key) BETWEEN 1 AND 200
    ),

  CONSTRAINT commercial_event_payload_object
    CHECK (jsonb_typeof(payload) = 'object')
);

