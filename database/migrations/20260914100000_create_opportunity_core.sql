CREATE TABLE ghm.opportunity (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_type_id bigint NOT NULL REFERENCES ghm.opportunity_type(id) ON DELETE RESTRICT,
  creator_account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  owner_business_id bigint REFERENCES ghm.business(id) ON DELETE RESTRICT,
  country_id bigint REFERENCES ghm.country(id) ON DELETE RESTRICT,
  currency_id bigint REFERENCES ghm.currency(id) ON DELETE RESTRICT,
  title text NOT NULL,
  description text NOT NULL,
  lifecycle_status text NOT NULL DEFAULT 'draft',
  visibility text NOT NULL DEFAULT 'private',
  budget_min numeric(14,2),
  budget_max numeric(14,2),
  opens_at timestamptz,
  closes_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT opportunity_title_valid CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  CONSTRAINT opportunity_description_valid CHECK (length(btrim(description)) BETWEEN 1 AND 10000),
  CONSTRAINT opportunity_lifecycle_valid CHECK (lifecycle_status IN ('draft','open','responding','evaluating','awarded','in_progress','completed','cancelled','archived')),
  CONSTRAINT opportunity_visibility_valid CHECK (visibility IN ('private','participants','authenticated','public')),
  CONSTRAINT opportunity_budget_min_valid CHECK (budget_min IS NULL OR budget_min >= 0),
  CONSTRAINT opportunity_budget_max_valid CHECK (budget_max IS NULL OR budget_max >= 0),
  CONSTRAINT opportunity_budget_range_valid CHECK (budget_min IS NULL OR budget_max IS NULL OR budget_max >= budget_min),
  CONSTRAINT opportunity_open_close_valid CHECK (opens_at IS NULL OR closes_at IS NULL OR closes_at >= opens_at),
  CONSTRAINT opportunity_public_not_draft CHECK (visibility <> 'public' OR lifecycle_status <> 'draft')
);

CREATE INDEX opportunity_type_status_created_idx ON ghm.opportunity (opportunity_type_id, lifecycle_status, created_at DESC);
CREATE INDEX opportunity_creator_created_idx ON ghm.opportunity (creator_account_id, created_at DESC);
CREATE INDEX opportunity_owner_business_created_idx ON ghm.opportunity (owner_business_id, created_at DESC) WHERE owner_business_id IS NOT NULL;
CREATE INDEX opportunity_visibility_status_created_idx ON ghm.opportunity (visibility, lifecycle_status, created_at DESC);
CREATE INDEX opportunity_country_status_created_idx ON ghm.opportunity (country_id, lifecycle_status, created_at DESC) WHERE country_id IS NOT NULL;

