CREATE TABLE ghm.opportunity_type (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  description text,
  version integer NOT NULL DEFAULT 1,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT opportunity_type_code_valid CHECK (code = lower(code) AND code ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  CONSTRAINT opportunity_type_name_valid CHECK (length(btrim(name)) BETWEEN 1 AND 120),
  CONSTRAINT opportunity_type_description_valid CHECK (description IS NULL OR length(btrim(description)) BETWEEN 1 AND 2000),
  CONSTRAINT opportunity_type_version_valid CHECK (version >= 1),
  CONSTRAINT opportunity_type_sort_order_valid CHECK (sort_order >= 0),
  CONSTRAINT opportunity_type_code_version_unique UNIQUE (code, version)
);

CREATE INDEX opportunity_type_active_sort_idx ON ghm.opportunity_type (is_active, sort_order, name);

CREATE TABLE ghm.country (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT country_code_valid CHECK (code = upper(code) AND code ~ '^[A-Z]{2}$'),
  CONSTRAINT country_name_valid CHECK (length(btrim(name)) BETWEEN 1 AND 120)
);

CREATE TABLE ghm.currency (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL UNIQUE,
  name text NOT NULL,
  symbol text,
  is_active boolean NOT NULL DEFAULT true,
  CONSTRAINT currency_code_valid CHECK (code = upper(code) AND code ~ '^[A-Z]{3}$'),
  CONSTRAINT currency_name_valid CHECK (length(btrim(name)) BETWEEN 1 AND 120)
);

