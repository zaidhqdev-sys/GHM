BEGIN;

-- Immutable catalogue of exact commercial document versions.
-- No legal text, approved hash, or active version is seeded by this migration.
CREATE TABLE ghm.commercial_document_version (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_type text NOT NULL,
  document_key text NOT NULL,
  version text NOT NULL,
  title text NOT NULL,
  content_sha256 text NOT NULL,
  document_uri text,
  jurisdiction_country_id bigint REFERENCES ghm.country(id) ON DELETE RESTRICT,
  plan_code text,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_document_type_valid
    CHECK (document_type IN ('trial_terms', 'subscription_terms')),
  CONSTRAINT commercial_document_key_valid
    CHECK (document_key = lower(document_key) AND document_key ~ '^[a-z][a-z0-9_-]{2,79}$'),
  CONSTRAINT commercial_document_version_valid
    CHECK (length(btrim(version)) BETWEEN 1 AND 80),
  CONSTRAINT commercial_document_title_valid
    CHECK (length(btrim(title)) BETWEEN 1 AND 160),
  CONSTRAINT commercial_document_sha256_valid
    CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
  CONSTRAINT commercial_document_uri_valid
    CHECK (document_uri IS NULL OR length(btrim(document_uri)) BETWEEN 1 AND 2048),
  CONSTRAINT commercial_document_plan_code_valid
    CHECK (plan_code IS NULL OR (plan_code = lower(plan_code) AND plan_code ~ '^[a-z][a-z0-9_]{2,49}$')),
  CONSTRAINT commercial_document_version_unique
    UNIQUE (document_type, document_key, version)
);

CREATE INDEX commercial_document_version_lookup_idx
  ON ghm.commercial_document_version (document_type, document_key, version);

-- Approval/withdrawal is represented by append-only state events rather
-- than mutable flags on the immutable document-version row.
CREATE TABLE ghm.commercial_document_status_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_version_id bigint NOT NULL
    REFERENCES ghm.commercial_document_version(id) ON DELETE RESTRICT,
  status text NOT NULL,
  actor_account_id bigint REFERENCES ghm.account_identity(id) ON DELETE SET NULL,
  source text NOT NULL,
  reason text,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

  CONSTRAINT commercial_document_status_valid
    CHECK (status IN ('draft', 'approved', 'withdrawn', 'superseded')),
  CONSTRAINT commercial_document_status_source_valid
    CHECK (length(btrim(source)) BETWEEN 1 AND 100),
  CONSTRAINT commercial_document_status_reason_valid
    CHECK (reason IS NULL OR length(reason) <= 1000),
  CONSTRAINT commercial_document_status_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX commercial_document_status_event_lookup_idx
  ON ghm.commercial_document_status_event (document_version_id, occurred_at DESC, id DESC);

-- Each row is evidence of an explicit acceptance of one exact document
-- version by one authenticated account for one canonical GHM Business.
CREATE TABLE ghm.commercial_consent_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  document_version_id bigint NOT NULL
    REFERENCES ghm.commercial_document_version(id) ON DELETE RESTRICT,
  consent_action text NOT NULL DEFAULT 'accepted',
  idempotency_key text NOT NULL,
  request_id text,
  source text NOT NULL,
  context jsonb NOT NULL DEFAULT '{}'::jsonb,
  accepted_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT commercial_consent_action_valid
    CHECK (consent_action = 'accepted'),
  CONSTRAINT commercial_consent_idempotency_valid
    CHECK (length(btrim(idempotency_key)) BETWEEN 8 AND 200),
  CONSTRAINT commercial_consent_request_id_valid
    CHECK (request_id IS NULL OR length(btrim(request_id)) BETWEEN 1 AND 200),
  CONSTRAINT commercial_consent_source_valid
    CHECK (length(btrim(source)) BETWEEN 1 AND 100),
  CONSTRAINT commercial_consent_context_object
    CHECK (jsonb_typeof(context) = 'object'),
  CONSTRAINT commercial_consent_idempotency_unique
    UNIQUE (idempotency_key)
);

CREATE INDEX commercial_consent_business_history_idx
  ON ghm.commercial_consent_event (business_id, accepted_at DESC, id DESC);
CREATE INDEX commercial_consent_account_history_idx
  ON ghm.commercial_consent_event (account_id, accepted_at DESC, id DESC);
CREATE INDEX commercial_consent_document_idx
  ON ghm.commercial_consent_event (document_version_id, accepted_at DESC);

-- Generic immutability guard used by all three evidence tables.
CREATE OR REPLACE FUNCTION ghm.reject_commercial_evidence_mutation()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, ghm
AS $$
BEGIN
  RAISE EXCEPTION 'commercial evidence is append-only'
    USING ERRCODE = '55000';
END;
$$;

ALTER FUNCTION ghm.reject_commercial_evidence_mutation() OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.reject_commercial_evidence_mutation() FROM PUBLIC;

CREATE TRIGGER commercial_document_version_immutable
BEFORE UPDATE OR DELETE ON ghm.commercial_document_version
FOR EACH ROW EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();
CREATE TRIGGER commercial_document_version_no_truncate
BEFORE TRUNCATE ON ghm.commercial_document_version
FOR EACH STATEMENT EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();

CREATE TRIGGER commercial_document_status_event_immutable
BEFORE UPDATE OR DELETE ON ghm.commercial_document_status_event
FOR EACH ROW EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();
CREATE TRIGGER commercial_document_status_event_no_truncate
BEFORE TRUNCATE ON ghm.commercial_document_status_event
FOR EACH STATEMENT EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();

CREATE TRIGGER commercial_consent_event_immutable
BEFORE UPDATE OR DELETE ON ghm.commercial_consent_event
FOR EACH ROW EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();
CREATE TRIGGER commercial_consent_event_no_truncate
BEFORE TRUNCATE ON ghm.commercial_consent_event
FOR EACH STATEMENT EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();

-- No application/runtime role receives direct read or write access yet.
-- The authenticated actor/approved-document write boundary is a later,
-- separately qualified stage. Migration authority alone owns this evidence.
GRANT SELECT, INSERT, UPDATE, DELETE ON
  ghm.commercial_document_version,
  ghm.commercial_document_status_event,
  ghm.commercial_consent_event
TO ghm_migrator;
GRANT USAGE, SELECT ON SEQUENCE
  ghm.commercial_document_version_id_seq,
  ghm.commercial_document_status_event_id_seq,
  ghm.commercial_consent_event_id_seq
TO ghm_migrator;

COMMENT ON TABLE ghm.commercial_document_version IS
  'Immutable registry of exact commercial legal document versions. No version is approved by insertion alone.';
COMMENT ON TABLE ghm.commercial_document_status_event IS
  'Append-only lifecycle evidence for commercial document approval, withdrawal and supersession.';
COMMENT ON TABLE ghm.commercial_consent_event IS
  'Append-only evidence of an account accepting an exact commercial document version for a canonical GHM Business.';
COMMENT ON FUNCTION ghm.reject_commercial_evidence_mutation() IS
  'Rejects UPDATE, DELETE and TRUNCATE against immutable commercial evidence tables.';

COMMIT;
