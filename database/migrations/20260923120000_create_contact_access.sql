-- Contact Access Slice A: dedicated entitlement persistence for Model A
-- (Business + Opportunity), promotional/manual grants only.
-- Construction-only for domain grant/check/revoke. No HTTP, payment,
-- provider, disclosure, or Enquiry redaction is authorized by this migration.

CREATE TABLE ghm.contact_access_entitlement (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  business_id bigint NOT NULL
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,

  opportunity_id bigint NOT NULL
    REFERENCES ghm.opportunity(id)
    ON DELETE RESTRICT,

  authorization_status text NOT NULL,

  grant_reason text NOT NULL,
  grant_source text NOT NULL,
  granted_by_account_id bigint
    REFERENCES ghm.account_identity(id)
    ON DELETE SET NULL,
  granted_at timestamptz NOT NULL DEFAULT now(),

  -- Future commercial-event linkage; unused by Slice A grant path.
  commercial_event_reference text,

  revoked_at timestamptz,
  revoked_by_account_id bigint
    REFERENCES ghm.account_identity(id)
    ON DELETE SET NULL,
  revocation_reason text,

  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT contact_access_authorization_status_valid
    CHECK (authorization_status IN ('active', 'revoked')),

  CONSTRAINT contact_access_grant_reason_valid
    CHECK (grant_reason = 'manual_promotional'),

  CONSTRAINT contact_access_grant_source_valid
    CHECK (length(btrim(grant_source)) BETWEEN 1 AND 100),

  CONSTRAINT contact_access_commercial_event_reference_valid
    CHECK (
      commercial_event_reference IS NULL
      OR length(btrim(commercial_event_reference)) BETWEEN 1 AND 200
    ),

  CONSTRAINT contact_access_revocation_reason_valid
    CHECK (
      revocation_reason IS NULL
      OR length(btrim(revocation_reason)) BETWEEN 1 AND 500
    ),

  CONSTRAINT contact_access_active_revocation_null
    CHECK (
      (
        authorization_status = 'active'
        AND revoked_at IS NULL
        AND revoked_by_account_id IS NULL
        AND revocation_reason IS NULL
      )
      OR (
        authorization_status = 'revoked'
        AND revoked_at IS NOT NULL
        AND revocation_reason IS NOT NULL
      )
    )
);

-- At most one active Contact Access entitlement per Business + Opportunity.
CREATE UNIQUE INDEX contact_access_one_active_uq
  ON ghm.contact_access_entitlement (business_id, opportunity_id)
  WHERE authorization_status = 'active';

CREATE INDEX contact_access_business_opportunity_idx
  ON ghm.contact_access_entitlement (business_id, opportunity_id, granted_at DESC, id DESC);

CREATE INDEX contact_access_opportunity_idx
  ON ghm.contact_access_entitlement (opportunity_id, id);

CREATE TABLE ghm.contact_access_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  entitlement_id bigint NOT NULL
    REFERENCES ghm.contact_access_entitlement(id)
    ON DELETE RESTRICT,

  business_id bigint NOT NULL
    REFERENCES ghm.business(id)
    ON DELETE RESTRICT,

  opportunity_id bigint NOT NULL
    REFERENCES ghm.opportunity(id)
    ON DELETE RESTRICT,

  event_type text NOT NULL,
  actor_account_id bigint
    REFERENCES ghm.account_identity(id)
    ON DELETE SET NULL,
  source text NOT NULL,
  reason text NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT contact_access_event_type_valid
    CHECK (event_type IN ('granted', 'revoked')),

  CONSTRAINT contact_access_event_source_valid
    CHECK (length(btrim(source)) BETWEEN 1 AND 100),

  CONSTRAINT contact_access_event_reason_valid
    CHECK (length(btrim(reason)) BETWEEN 1 AND 500),

  CONSTRAINT contact_access_event_payload_object
    CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX contact_access_event_entitlement_idx
  ON ghm.contact_access_event (entitlement_id, occurred_at DESC, id DESC);

CREATE INDEX contact_access_event_business_opportunity_idx
  ON ghm.contact_access_event (business_id, opportunity_id, occurred_at DESC, id DESC);

ALTER TABLE ghm.contact_access_entitlement OWNER TO ghm_schema_owner;
ALTER TABLE ghm.contact_access_event OWNER TO ghm_schema_owner;

