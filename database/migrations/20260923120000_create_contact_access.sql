CREATE OR REPLACE FUNCTION ghm.grant_contact_access_manual(
  p_business_id bigint,
  p_opportunity_id bigint,
  p_grant_source text
)
RETURNS TABLE (
  id bigint,
  business_id bigint,
  opportunity_id bigint,
  authorization_status text,
  grant_reason text,
  grant_source text,
  granted_by_account_id bigint,
  granted_at timestamptz,
  commercial_event_reference text,
  revoked_at timestamptz,
  revoked_by_account_id bigint,
  revocation_reason text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
DECLARE
  normalized_source text;
  opportunity_lifecycle text;
  enquiry_count integer;
  enquiry_business_id bigint;
  actor_account_id bigint;
  existing ghm.contact_access_entitlement%ROWTYPE;
  inserted ghm.contact_access_entitlement%ROWTYPE;
BEGIN
  BEGIN
    actor_account_id := nullif(btrim(current_setting('ghm.actor_account_id', true)), '')::bigint;
  EXCEPTION
    WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'Contact Access actor context required';
  END;

  IF actor_account_id IS NULL OR actor_account_id <= 0 THEN
    RAISE EXCEPTION 'Contact Access actor context required';
  END IF;

  IF p_business_id IS NULL OR p_business_id <= 0 THEN
    RAISE EXCEPTION 'businessId must be a positive integer';
  END IF;

  IF p_opportunity_id IS NULL OR p_opportunity_id <= 0 THEN
    RAISE EXCEPTION 'opportunityId must be a positive integer';
  END IF;

  normalized_source := btrim(p_grant_source);
  IF normalized_source IS NULL OR length(normalized_source) < 1 OR length(normalized_source) > 100 THEN
    RAISE EXCEPTION 'grantSource must be between 1 and 100 characters';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM ghm.business b
     WHERE b.id = p_business_id
       AND b.is_active = true
  ) THEN
    RAISE EXCEPTION 'Business is not eligible for Contact Access';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM ghm.business_membership bm
     WHERE bm.business_id = p_business_id
       AND bm.account_id = actor_account_id
       AND bm.membership_status = 'active'
       AND bm.membership_role IN ('owner', 'administrator')
  ) THEN
    RAISE EXCEPTION 'Business management permission required';
  END IF;

  SELECT o.lifecycle_status INTO opportunity_lifecycle
    FROM ghm.opportunity o
   WHERE o.id = p_opportunity_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Opportunity not found';
  END IF;

  IF opportunity_lifecycle NOT IN ('open', 'responding', 'evaluating') THEN
    RAISE EXCEPTION 'Opportunity is not eligible for Contact Access grant';
  END IF;

  SELECT COUNT(*), MIN(e.business_id)
    INTO enquiry_count, enquiry_business_id
    FROM ghm.enquiry e
   WHERE e.opportunity_id = p_opportunity_id;

  IF enquiry_count = 0 THEN
    RAISE EXCEPTION 'Opportunity is not Enquiry-backed';
  END IF;

  IF enquiry_count > 1 THEN
    RAISE EXCEPTION 'Opportunity Enquiry association is ambiguous';
  END IF;

  IF enquiry_business_id IS DISTINCT FROM p_business_id THEN
    RAISE EXCEPTION 'Contact Access Business does not match Enquiry recipient';
  END IF;

  -- Serialize concurrent grants for the same Business+Opportunity pair.
  PERFORM pg_advisory_xact_lock(
    hashtext('ghm.contact_access.grant.business:' || p_business_id::text),
    hashtext('ghm.contact_access.grant.opportunity:' || p_opportunity_id::text)
  );

  SELECT * INTO existing
    FROM ghm.contact_access_entitlement cae
   WHERE cae.business_id = p_business_id
     AND cae.opportunity_id = p_opportunity_id
     AND cae.authorization_status = 'active'
   FOR UPDATE;

  IF FOUND THEN
    RETURN QUERY
    SELECT
      existing.id,
      existing.business_id,
      existing.opportunity_id,
      existing.authorization_status,
      existing.grant_reason,
      existing.grant_source,
      existing.granted_by_account_id,
      existing.granted_at,
      existing.commercial_event_reference,
      existing.revoked_at,
      existing.revoked_by_account_id,
      existing.revocation_reason,
      existing.created_at,
      existing.updated_at;
    RETURN;
  END IF;

  BEGIN
    INSERT INTO ghm.contact_access_entitlement (
      business_id,
      opportunity_id,
      authorization_status,
      grant_reason,
      grant_source,
      granted_by_account_id,
      granted_at
    ) VALUES (
      p_business_id,
      p_opportunity_id,
      'active',
      'manual_promotional',
      normalized_source,
      actor_account_id,
      now()
    )
    RETURNING * INTO inserted;
  EXCEPTION
    WHEN unique_violation THEN
      SELECT * INTO existing
        FROM ghm.contact_access_entitlement cae
       WHERE cae.business_id = p_business_id
         AND cae.opportunity_id = p_opportunity_id
         AND cae.authorization_status = 'active'
       FOR UPDATE;

      IF NOT FOUND THEN
        RAISE;
      END IF;

      RETURN QUERY
      SELECT
        existing.id,
        existing.business_id,
        existing.opportunity_id,
        existing.authorization_status,
        existing.grant_reason,
        existing.grant_source,
        existing.granted_by_account_id,
        existing.granted_at,
        existing.commercial_event_reference,
        existing.revoked_at,
        existing.revoked_by_account_id,
        existing.revocation_reason,
        existing.created_at,
        existing.updated_at;
      RETURN;
  END;

  INSERT INTO ghm.contact_access_event (
    entitlement_id,
    business_id,
    opportunity_id,
    event_type,
    actor_account_id,
    source,
    reason,
    payload
  ) VALUES (
    inserted.id,
    inserted.business_id,
    inserted.opportunity_id,
    'granted',
    actor_account_id,
    normalized_source,
    'manual_promotional',
    jsonb_build_object('grant_reason', 'manual_promotional')
  );

  RETURN QUERY
  SELECT
    inserted.id,
    inserted.business_id,
    inserted.opportunity_id,
    inserted.authorization_status,
    inserted.grant_reason,
    inserted.grant_source,
    inserted.granted_by_account_id,
    inserted.granted_at,
    inserted.commercial_event_reference,
    inserted.revoked_at,
    inserted.revoked_by_account_id,
    inserted.revocation_reason,
    inserted.created_at,
    inserted.updated_at;
END;
$$;

