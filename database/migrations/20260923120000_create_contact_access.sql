CREATE OR REPLACE FUNCTION ghm.revoke_contact_access(
  p_business_id bigint,
  p_opportunity_id bigint,
  p_revocation_reason text
)
RETURNS TABLE (
  id bigint,
  business_id bigint,
  opportunity_id bigint,
  authorization_status text,
  grant_reason text,
  grant_source text,
  granted_by_account_id bigint,
  granted_at timestamptz,
  commercial_event_reference text,
  revoked_at timestamptz,
  revoked_by_account_id bigint,
  revocation_reason text,
  created_at timestamptz,
  updated_at timestamptz
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
DECLARE
  normalized_reason text;
  actor_account_id bigint;
  existing ghm.contact_access_entitlement%ROWTYPE;
  updated ghm.contact_access_entitlement%ROWTYPE;
BEGIN
  BEGIN
    actor_account_id := nullif(btrim(current_setting('ghm.actor_account_id', true)), '')::bigint;
  EXCEPTION
    WHEN invalid_text_representation THEN
      RAISE EXCEPTION 'Contact Access actor context required';
  END;

  IF actor_account_id IS NULL OR actor_account_id <= 0 THEN
    RAISE EXCEPTION 'Contact Access actor context required';
  END IF;

  IF p_business_id IS NULL OR p_business_id <= 0 THEN
    RAISE EXCEPTION 'businessId must be a positive integer';
  END IF;

  IF p_opportunity_id IS NULL OR p_opportunity_id <= 0 THEN
    RAISE EXCEPTION 'opportunityId must be a positive integer';
  END IF;

  normalized_reason := btrim(p_revocation_reason);
  IF normalized_reason IS NULL OR length(normalized_reason) < 1 OR length(normalized_reason) > 500 THEN
    RAISE EXCEPTION 'revocationReason must be between 1 and 500 characters';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM ghm.business_membership bm
     WHERE bm.business_id = p_business_id
       AND bm.account_id = actor_account_id
       AND bm.membership_status = 'active'
       AND bm.membership_role IN ('owner', 'administrator')
  ) THEN
    RAISE EXCEPTION 'Business management permission required';
  END IF;

  SELECT * INTO existing
    FROM ghm.contact_access_entitlement cae
   WHERE cae.business_id = p_business_id
     AND cae.opportunity_id = p_opportunity_id
     AND cae.authorization_status = 'active'
   FOR UPDATE;

  IF NOT FOUND THEN
    IF EXISTS (
      SELECT 1 FROM ghm.contact_access_entitlement cae
       WHERE cae.business_id = p_business_id
         AND cae.opportunity_id = p_opportunity_id
         AND cae.authorization_status = 'revoked'
    ) THEN
      RAISE EXCEPTION 'Contact Access entitlement is not active';
    END IF;
    RAISE EXCEPTION 'Contact Access entitlement not found';
  END IF;

  UPDATE ghm.contact_access_entitlement
     SET authorization_status = 'revoked',
         revoked_at = now(),
         revoked_by_account_id = actor_account_id,
         revocation_reason = normalized_reason
   WHERE ghm.contact_access_entitlement.id = existing.id
  RETURNING * INTO updated;

  INSERT INTO ghm.contact_access_event (
    entitlement_id,
    business_id,
    opportunity_id,
    event_type,
    actor_account_id,
    source,
    reason,
    payload
  ) VALUES (
    updated.id,
    updated.business_id,
    updated.opportunity_id,
    'revoked',
    actor_account_id,
    'manual_revoke',
    normalized_reason,
    jsonb_build_object('prior_status', 'active')
  );

  RETURN QUERY
  SELECT
    updated.id,
    updated.business_id,
    updated.opportunity_id,
    updated.authorization_status,
    updated.grant_reason,
    updated.grant_source,
    updated.granted_by_account_id,
    updated.granted_at,
    updated.commercial_event_reference,
    updated.revoked_at,
    updated.revoked_by_account_id,
    updated.revocation_reason,
    updated.created_at,
    updated.updated_at;
END;
$$;

