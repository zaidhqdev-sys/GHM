-- First-party GHM replacement for Connect's legacy business engagement RPC.
-- Only authenticated events for currently approved public listings are accepted.
CREATE TABLE ghm.business_engagement_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  event_type text NOT NULL CHECK (event_type IN (
    'profile_view', 'save', 'whatsapp', 'call', 'website_visit', 'direction_request', 'share'
  )),
  event_context jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(event_context) = 'object'),
  source text NOT NULL DEFAULT 'web' CHECK (source IN ('web', 'mobile')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX business_engagement_event_business_created_idx
  ON ghm.business_engagement_event (business_id, created_at DESC);
CREATE INDEX business_engagement_event_account_created_idx
  ON ghm.business_engagement_event (account_id, created_at DESC);

ALTER TABLE ghm.business_engagement_event OWNER TO ghm_schema_owner;
REVOKE ALL ON TABLE ghm.business_engagement_event FROM PUBLIC, ghm_migrator;
GRANT INSERT (business_id, account_id, event_type, event_context, source),
  SELECT (id, business_id, account_id, event_type, event_context, source, created_at)
  ON TABLE ghm.business_engagement_event TO ghm_runtime;
GRANT USAGE, SELECT ON SEQUENCE ghm.business_engagement_event_id_seq TO ghm_runtime;
