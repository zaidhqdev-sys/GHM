BEGIN;

CREATE TABLE ghm.relationship_type (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  description text,
  directionality text NOT NULL DEFAULT 'directed',
  version integer NOT NULL DEFAULT 1,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT relationship_type_code_format CHECK (code ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT relationship_type_directionality_check CHECK (directionality IN ('directed', 'reciprocal')),
  CONSTRAINT relationship_type_version_positive CHECK (version > 0),
  CONSTRAINT relationship_type_sort_order_nonnegative CHECK (sort_order >= 0),
  CONSTRAINT relationship_type_code_version_unique UNIQUE (code, version),
  CONSTRAINT relationship_type_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE ghm.business_relationship (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  relationship_type_id bigint NOT NULL REFERENCES ghm.relationship_type(id) ON DELETE RESTRICT,
  source_business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  target_business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  originating_opportunity_id bigint REFERENCES ghm.opportunity(id) ON DELETE RESTRICT,
  lifecycle_status text NOT NULL DEFAULT 'proposed',
  provenance_type text NOT NULL,
  authority_type text NOT NULL,
  verification_status text NOT NULL DEFAULT 'unverified',
  visibility text NOT NULL DEFAULT 'private',
  valid_from timestamptz NOT NULL DEFAULT now(),
  valid_until timestamptz,
  created_by bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_relationship_distinct_businesses CHECK (source_business_id <> target_business_id),
  CONSTRAINT business_relationship_lifecycle_status_check CHECK (lifecycle_status IN ('proposed', 'active', 'suspended', 'ended', 'rejected')),
  CONSTRAINT business_relationship_provenance_type_check CHECK (provenance_type IN ('participant_assertion', 'platform_verified', 'platform_observed', 'authorized_import', 'derived')),
  CONSTRAINT business_relationship_authority_type_check CHECK (authority_type IN ('source_business', 'target_business', 'mutual', 'platform', 'external_authority')),
  CONSTRAINT business_relationship_verification_status_check CHECK (verification_status IN ('unverified', 'pending', 'verified', 'rejected', 'revoked')),
  CONSTRAINT business_relationship_visibility_check CHECK (visibility IN ('private', 'participants', 'authenticated', 'public')),
  CONSTRAINT business_relationship_valid_range_check CHECK (valid_until IS NULL OR valid_until > valid_from),
  CONSTRAINT business_relationship_metadata_object CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE UNIQUE INDEX business_relationship_active_identity_unique
  ON ghm.business_relationship (relationship_type_id, source_business_id, target_business_id)
  WHERE lifecycle_status IN ('proposed', 'active', 'suspended');
CREATE INDEX business_relationship_source_business_idx ON ghm.business_relationship (source_business_id, lifecycle_status);
CREATE INDEX business_relationship_target_business_idx ON ghm.business_relationship (target_business_id, lifecycle_status);
CREATE INDEX business_relationship_opportunity_idx ON ghm.business_relationship (originating_opportunity_id) WHERE originating_opportunity_id IS NOT NULL;
CREATE INDEX business_relationship_visibility_idx ON ghm.business_relationship (visibility, verification_status, lifecycle_status);

CREATE TABLE ghm.outcome_type (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text NOT NULL,
  name text NOT NULL,
  description text,
  version integer NOT NULL DEFAULT 1,
  is_active boolean NOT NULL DEFAULT true,
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT outcome_type_code_format CHECK (code ~ '^[a-z][a-z0-9_]*$'),
  CONSTRAINT outcome_type_version_positive CHECK (version > 0),
  CONSTRAINT outcome_type_sort_order_nonnegative CHECK (sort_order >= 0),
  CONSTRAINT outcome_type_code_version_unique UNIQUE (code, version),
  CONSTRAINT outcome_type_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE ghm.outcome (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  outcome_type_id bigint NOT NULL REFERENCES ghm.outcome_type(id) ON DELETE RESTRICT,
  subject_business_id bigint REFERENCES ghm.business(id) ON DELETE RESTRICT,
  counterparty_business_id bigint REFERENCES ghm.business(id) ON DELETE RESTRICT,
  opportunity_id bigint REFERENCES ghm.opportunity(id) ON DELETE RESTRICT,
  business_relationship_id bigint REFERENCES ghm.business_relationship(id) ON DELETE RESTRICT,
  assertion_source text NOT NULL,
  verification_status text NOT NULL DEFAULT 'unverified',
  lifecycle_status text NOT NULL DEFAULT 'recorded',
  visibility text NOT NULL DEFAULT 'private',
  summary text,
  evidence_reference text,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  created_by bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT outcome_distinct_businesses CHECK (subject_business_id IS NULL OR counterparty_business_id IS NULL OR subject_business_id <> counterparty_business_id),
  CONSTRAINT outcome_has_subject_context CHECK (
    subject_business_id IS NOT NULL OR counterparty_business_id IS NOT NULL
    OR opportunity_id IS NOT NULL OR business_relationship_id IS NOT NULL
  ),
  CONSTRAINT outcome_assertion_source_check CHECK (assertion_source IN ('participant_assertion', 'platform_verified', 'platform_observed', 'authorized_import', 'derived')),
  CONSTRAINT outcome_verification_status_check CHECK (verification_status IN ('unverified', 'pending', 'verified', 'rejected', 'revoked')),
  CONSTRAINT outcome_lifecycle_status_check CHECK (lifecycle_status IN ('recorded', 'confirmed', 'disputed', 'superseded', 'voided')),
  CONSTRAINT outcome_visibility_check CHECK (visibility IN ('private', 'participants', 'authenticated', 'public')),
  CONSTRAINT outcome_metadata_object CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX outcome_subject_business_idx ON ghm.outcome (subject_business_id, lifecycle_status) WHERE subject_business_id IS NOT NULL;
CREATE INDEX outcome_counterparty_business_idx ON ghm.outcome (counterparty_business_id, lifecycle_status) WHERE counterparty_business_id IS NOT NULL;
CREATE INDEX outcome_opportunity_idx ON ghm.outcome (opportunity_id, lifecycle_status) WHERE opportunity_id IS NOT NULL;
CREATE INDEX outcome_relationship_idx ON ghm.outcome (business_relationship_id, lifecycle_status) WHERE business_relationship_id IS NOT NULL;
CREATE INDEX outcome_type_idx ON ghm.outcome (outcome_type_id, occurred_at DESC);
CREATE INDEX outcome_visibility_idx ON ghm.outcome (visibility, verification_status, lifecycle_status);

ALTER TABLE ghm.relationship_type OWNER TO ghm_schema_owner;
ALTER TABLE ghm.business_relationship OWNER TO ghm_schema_owner;
ALTER TABLE ghm.outcome_type OWNER TO ghm_schema_owner;
ALTER TABLE ghm.outcome OWNER TO ghm_schema_owner;

REVOKE ALL ON ghm.relationship_type, ghm.business_relationship, ghm.outcome_type, ghm.outcome FROM PUBLIC, ghm_migrator;
GRANT SELECT ON ghm.relationship_type, ghm.business_relationship, ghm.outcome_type, ghm.outcome TO ghm_runtime;
REVOKE INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER ON ghm.relationship_type, ghm.business_relationship, ghm.outcome_type, ghm.outcome FROM ghm_runtime;

