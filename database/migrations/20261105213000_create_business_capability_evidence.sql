-- Provider-neutral, bounded reference-only evidence for canonical Business Capability assertions.
-- Construction-only. No persistent database migration or production cutover is authorized.

CREATE TABLE ghm.business_capability_evidence (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_capability_id bigint NOT NULL REFERENCES ghm.business_capability(id) ON DELETE RESTRICT,
  evidence_type text NOT NULL,
  title text NOT NULL,
  description text,
  issuer_name text,
  reference_number text,
  evidence_url text,
  issued_on date,
  expires_on date,
  visibility text NOT NULL DEFAULT 'private',
  verification_status text NOT NULL DEFAULT 'pending',
  submitted_by bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  submitted_at timestamptz NOT NULL DEFAULT now(),
  verified_by bigint REFERENCES ghm.account_identity(id) ON DELETE SET NULL,
  verified_at timestamptz,
  verification_reason text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_capability_evidence_type_check CHECK (evidence_type IN ('accreditation','certification','licence','project_record','customer_reference','portfolio_reference','other')),
  CONSTRAINT business_capability_evidence_title_check CHECK (char_length(btrim(title)) BETWEEN 1 AND 160),
  CONSTRAINT business_capability_evidence_description_check CHECK (description IS NULL OR char_length(btrim(description)) BETWEEN 1 AND 2000),
  CONSTRAINT business_capability_evidence_issuer_check CHECK (issuer_name IS NULL OR char_length(btrim(issuer_name)) BETWEEN 1 AND 160),
  CONSTRAINT business_capability_evidence_reference_check CHECK (reference_number IS NULL OR char_length(btrim(reference_number)) BETWEEN 1 AND 160),
  CONSTRAINT business_capability_evidence_url_check CHECK (evidence_url IS NULL OR (char_length(btrim(evidence_url)) BETWEEN 8 AND 500 AND evidence_url ~* '^https://')),
  CONSTRAINT business_capability_evidence_dates_check CHECK (expires_on IS NULL OR issued_on IS NULL OR expires_on > issued_on),
  CONSTRAINT business_capability_evidence_visibility_check CHECK (visibility IN ('private','authenticated','public')),
  CONSTRAINT business_capability_evidence_status_check CHECK (verification_status IN ('pending','verified','rejected','revoked','expired')),
  CONSTRAINT business_capability_evidence_reason_check CHECK (verification_reason IS NULL OR char_length(btrim(verification_reason)) BETWEEN 1 AND 1000),
  CONSTRAINT business_capability_evidence_verification_state_check CHECK (
    (verification_status = 'pending' AND verified_by IS NULL AND verified_at IS NULL AND verification_reason IS NULL)
    OR (verification_status = 'verified' AND verified_by IS NOT NULL AND verified_at IS NOT NULL AND verification_reason IS NULL)
    OR (verification_status IN ('rejected','revoked') AND verified_by IS NOT NULL AND verified_at IS NOT NULL AND verification_reason IS NOT NULL)
    OR (verification_status = 'expired' AND verified_at IS NOT NULL)
  ),
  CONSTRAINT business_capability_evidence_reference_unique UNIQUE (business_capability_id,evidence_type,reference_number)
);

CREATE INDEX business_capability_evidence_assertion_idx
  ON ghm.business_capability_evidence (business_capability_id,verification_status,submitted_at,id);
CREATE INDEX business_capability_evidence_pending_idx
  ON ghm.business_capability_evidence (submitted_at,id)
  WHERE verification_status = 'pending';

ALTER TABLE ghm.business_capability_evidence OWNER TO ghm_schema_owner;
GRANT USAGE ON SCHEMA ghm TO ghm_runtime;
GRANT SELECT ON ghm.business_capability_evidence TO ghm_runtime;
GRANT INSERT (business_capability_id,evidence_type,title,description,issuer_name,reference_number,evidence_url,issued_on,expires_on,visibility,verification_status,submitted_by)
  ON ghm.business_capability_evidence TO ghm_runtime;
GRANT USAGE ON SEQUENCE ghm.business_capability_evidence_id_seq TO ghm_runtime;

CREATE OR REPLACE FUNCTION ghm.transition_business_capability_evidence(
  p_evidence_id bigint,
  p_decision text,
  p_verifier_id bigint,
  p_reason text DEFAULT NULL
)
RETURNS ghm.business_capability_evidence
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
DECLARE
  v_evidence ghm.business_capability_evidence%ROWTYPE;
  v_reason text := NULLIF(btrim(p_reason), '');
  v_role text;
  v_verified_count integer;
BEGIN
  IF p_evidence_id IS NULL OR p_evidence_id <= 0 OR p_verifier_id IS NULL OR p_verifier_id <= 0 THEN
    RAISE EXCEPTION 'Evidence and verifier identifiers must be positive integers';
  END IF;
  SELECT role INTO v_role FROM ghm.account_identity WHERE id = p_verifier_id;
  IF v_role IS DISTINCT FROM 'admin' THEN RAISE EXCEPTION 'Capability evidence verifier authority required'; END IF;
  SELECT * INTO v_evidence FROM ghm.business_capability_evidence WHERE id = p_evidence_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Capability evidence not found'; END IF;
  IF v_evidence.submitted_by = p_verifier_id THEN RAISE EXCEPTION 'Self-verification is not permitted'; END IF;
  IF p_decision NOT IN ('verified','rejected','revoked') THEN RAISE EXCEPTION 'Evidence decision is invalid'; END IF;
  IF p_decision IN ('rejected','revoked') AND (v_reason IS NULL OR char_length(v_reason) > 1000) THEN
    RAISE EXCEPTION 'A bounded reason is required for rejection or revocation';
  END IF;
  IF NOT ((v_evidence.verification_status = 'pending' AND p_decision IN ('verified','rejected'))
       OR (v_evidence.verification_status = 'verified' AND p_decision = 'revoked')) THEN
    RAISE EXCEPTION 'Evidence is not in a reviewable state';
  END IF;

  UPDATE ghm.business_capability_evidence
     SET verification_status = p_decision,
         verified_by = p_verifier_id,
         verified_at = clock_timestamp(),
         verification_reason = CASE WHEN p_decision = 'verified' THEN NULL ELSE v_reason END,
         updated_at = clock_timestamp()
   WHERE id = p_evidence_id
   RETURNING * INTO v_evidence;

  SELECT count(*)::integer INTO v_verified_count
    FROM ghm.business_capability_evidence
   WHERE business_capability_id = v_evidence.business_capability_id
     AND verification_status = 'verified'
     AND (expires_on IS NULL OR expires_on >= current_date);

  UPDATE ghm.business_capability
     SET verification_status = CASE
           WHEN v_verified_count > 0 THEN 'verified'
           WHEN p_decision = 'rejected' THEN 'rejected'
           ELSE 'revoked'
         END,
         verified_by = p_verifier_id,
         verified_at = clock_timestamp(),
         verification_reason = CASE WHEN v_verified_count > 0 THEN NULL ELSE v_reason END,
         updated_at = clock_timestamp()
   WHERE id = v_evidence.business_capability_id;

  RETURN v_evidence;
END;
$$;

