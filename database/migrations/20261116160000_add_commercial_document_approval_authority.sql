BEGIN;

-- Legal approval authority is distinct from GHM technical administration.
-- Authority is represented as immutable grant/revoke events. No authority is
-- seeded here and no application role may read or write this registry.
CREATE TABLE ghm.commercial_document_approval_authority_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  authority_id uuid NOT NULL,
  event_type text NOT NULL,
  document_type text NOT NULL,
  document_key text NOT NULL,
  jurisdiction_country_id bigint REFERENCES ghm.country(id) ON DELETE RESTRICT,
  authority_account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  recorded_by_account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  reason text NOT NULL,
  request_id text,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,

  CONSTRAINT commercial_document_authority_event_type_valid
    CHECK (event_type IN ('granted', 'revoked')),
  CONSTRAINT commercial_document_authority_document_type_valid
    CHECK (document_type IN ('trial_terms', 'subscription_terms')),
  CONSTRAINT commercial_document_authority_document_key_valid
    CHECK (document_key = lower(document_key) AND document_key ~ '^[a-z][a-z0-9_-]{2,79}$'),
  CONSTRAINT commercial_document_authority_reason_valid
    CHECK (length(btrim(reason)) BETWEEN 1 AND 1000),
  CONSTRAINT commercial_document_authority_request_id_valid
    CHECK (request_id IS NULL OR length(btrim(request_id)) BETWEEN 1 AND 200),
  CONSTRAINT commercial_document_authority_metadata_object
    CHECK (jsonb_typeof(metadata) = 'object')
);

CREATE INDEX commercial_document_authority_history_idx
  ON ghm.commercial_document_approval_authority_event
     (authority_id, occurred_at DESC, id DESC);
CREATE INDEX commercial_document_authority_scope_idx
  ON ghm.commercial_document_approval_authority_event
     (document_type, document_key, jurisdiction_country_id, occurred_at DESC, id DESC);

-- An approval event must cite the exact grant event authorizing its actor.
-- The eventual write function must also verify that the grant remains active
-- for the document scope at approval time; this FK alone is not authorization.
ALTER TABLE ghm.commercial_document_status_event
  ADD COLUMN approval_authority_event_id bigint
    REFERENCES ghm.commercial_document_approval_authority_event(id) ON DELETE RESTRICT;

ALTER TABLE ghm.commercial_document_status_event
  ADD CONSTRAINT commercial_document_approval_authority_required
  CHECK (
    (status = 'approved' AND approval_authority_event_id IS NOT NULL)
    OR
    (status <> 'approved' AND approval_authority_event_id IS NULL)
  );

-- Reuse the existing append-only trigger function.
CREATE TRIGGER commercial_document_approval_authority_event_immutable
BEFORE UPDATE OR DELETE ON ghm.commercial_document_approval_authority_event
FOR EACH ROW EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();
CREATE TRIGGER commercial_document_approval_authority_event_no_truncate
BEFORE TRUNCATE ON ghm.commercial_document_approval_authority_event
FOR EACH STATEMENT EXECUTE FUNCTION ghm.reject_commercial_evidence_mutation();

-- Deliberately no runtime, gateway, PUBLIC, or application access. The
-- authenticated authority-management and approval operation is a later slice.
GRANT SELECT, INSERT, UPDATE, DELETE ON
  ghm.commercial_document_approval_authority_event
TO ghm_migrator;
GRANT USAGE, SELECT ON SEQUENCE
  ghm.commercial_document_approval_authority_event_id_seq
TO ghm_migrator;

COMMENT ON TABLE ghm.commercial_document_approval_authority_event IS
  'Append-only grant/revoke evidence for scoped commercial legal-document approval authority. GHM admin status alone does not confer this authority.';
COMMENT ON COLUMN ghm.commercial_document_status_event.approval_authority_event_id IS
  'Exact authority grant event cited by an approval; the governed write function must verify actor, scope and continuing grant validity.';

COMMIT;
