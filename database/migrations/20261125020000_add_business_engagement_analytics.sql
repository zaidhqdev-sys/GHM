BEGIN;

ALTER TABLE ghm.business
  ADD COLUMN IF NOT EXISTS profile_views bigint NOT NULL DEFAULT 0;

CREATE TABLE ghm.business_engagement_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE CASCADE,
  event_type text NOT NULL,
  actor_account_id bigint REFERENCES ghm.account_identity(id) ON DELETE SET NULL,
  source text NOT NULL,
  context jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT business_engagement_event_type_ck CHECK (event_type IN (
    'profile_view','call','whatsapp','quote_request','website_visit',
    'direction_request','save','share'
  )),
  CONSTRAINT business_engagement_event_source_ck CHECK (source IN ('web','mobile')),
  CONSTRAINT business_engagement_event_context_object_ck CHECK (jsonb_typeof(context) = 'object'),
  CONSTRAINT business_engagement_event_context_size_ck CHECK (octet_length(context::text) <= 4000),
  CONSTRAINT business_engagement_event_time_ck CHECK (occurred_at <= now() + interval '5 minutes')
);

CREATE INDEX business_engagement_event_business_time_idx
  ON ghm.business_engagement_event (business_id, occurred_at DESC, id DESC);
CREATE INDEX business_engagement_event_business_type_time_idx
  ON ghm.business_engagement_event (business_id, event_type, occurred_at DESC);

CREATE TABLE ghm.business_profile_view_visitor (
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE CASCADE,
  visitor_id text NOT NULL,
  last_viewed_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (business_id, visitor_id),
  CONSTRAINT business_profile_view_visitor_id_ck CHECK (length(btrim(visitor_id)) BETWEEN 1 AND 128)
);
CREATE INDEX business_profile_view_visitor_last_viewed_idx
  ON ghm.business_profile_view_visitor (last_viewed_at DESC);

CREATE FUNCTION ghm.increment_business_profile_views()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF NEW.event_type = 'profile_view' THEN
    UPDATE ghm.business
       SET profile_views = profile_views + 1,
           updated_at = now()
     WHERE id = NEW.business_id;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER business_engagement_profile_view_counter
AFTER INSERT ON ghm.business_engagement_event
FOR EACH ROW
WHEN (NEW.event_type = 'profile_view')
EXECUTE FUNCTION ghm.increment_business_profile_views();

GRANT USAGE ON SCHEMA ghm TO ghm_runtime;
GRANT SELECT, INSERT ON TABLE ghm.business_engagement_event TO ghm_runtime;
GRANT USAGE ON SEQUENCE ghm.business_engagement_event_id_seq TO ghm_runtime;
GRANT SELECT, INSERT, UPDATE ON TABLE ghm.business_profile_view_visitor TO ghm_runtime;
GRANT SELECT, UPDATE (profile_views, updated_at) ON TABLE ghm.business TO ghm_runtime;

COMMIT;
