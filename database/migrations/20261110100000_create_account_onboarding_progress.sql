BEGIN;

CREATE TABLE ghm.account_onboarding_progress (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id bigint NOT NULL REFERENCES ghm.account_identity(id) ON DELETE CASCADE,
  journey_id text NOT NULL,
  step_id text NOT NULL,
  status text NOT NULL DEFAULT 'pending',
  first_started_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  dismissed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT account_onboarding_progress_identity_unique UNIQUE (account_id, journey_id, step_id),
  CONSTRAINT account_onboarding_progress_journey_valid CHECK (journey_id ~ '^[a-z][a-z0-9_]{2,79}_v[1-9][0-9]*$'),
  CONSTRAINT account_onboarding_progress_step_valid CHECK (step_id ~ '^[a-z][a-z0-9_]{1,79}$'),
  CONSTRAINT account_onboarding_progress_status_valid CHECK (status IN ('pending', 'completed', 'dismissed')),
  CONSTRAINT account_onboarding_progress_lifecycle_valid CHECK (
    (status = 'pending' AND completed_at IS NULL AND dismissed_at IS NULL)
    OR (status = 'completed' AND completed_at IS NOT NULL AND dismissed_at IS NULL)
    OR (status = 'dismissed' AND completed_at IS NULL AND dismissed_at IS NOT NULL)
  ),
  CONSTRAINT account_onboarding_progress_time_valid CHECK (
    first_started_at >= created_at
    AND updated_at >= created_at
    AND (completed_at IS NULL OR completed_at >= first_started_at)
    AND (dismissed_at IS NULL OR dismissed_at >= first_started_at)
  )
);

CREATE INDEX account_onboarding_progress_account_journey_idx
  ON ghm.account_onboarding_progress (account_id, journey_id, created_at, step_id);

ALTER TABLE ghm.account_onboarding_progress OWNER TO ghm_schema_owner;
REVOKE ALL ON ghm.account_onboarding_progress FROM PUBLIC, ghm_migrator;
GRANT SELECT, INSERT, UPDATE ON ghm.account_onboarding_progress TO ghm_runtime;
REVOKE DELETE, TRUNCATE, REFERENCES, TRIGGER ON ghm.account_onboarding_progress FROM ghm_runtime;

GRANT USAGE, SELECT ON SEQUENCE ghm.account_onboarding_progress_id_seq TO ghm_runtime;

COMMIT;
