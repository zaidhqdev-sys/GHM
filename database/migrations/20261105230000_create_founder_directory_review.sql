-- Founder-controlled Business directory listing review.
-- The reviewer allowlist is deliberately empty: canonical reviewer mapping and
-- explicit approval must happen in a later, separately reviewed migration.
-- No production seed, deployment, or cutover is included.

ALTER TABLE ghm.business
  ADD COLUMN IF NOT EXISTS directory_review_submitted_at timestamptz,
  ADD COLUMN IF NOT EXISTS directory_review_last_reason text,
  ADD COLUMN IF NOT EXISTS directory_review_last_event_type text;

ALTER TABLE ghm.business
  ADD CONSTRAINT business_directory_review_status_check
  CHECK (verification_status IN ('unverified','under_review','information_requested','approved','rejected'));

ALTER TABLE ghm.business
  ADD CONSTRAINT business_directory_review_reason_check
  CHECK (directory_review_last_reason IS NULL OR char_length(btrim(directory_review_last_reason)) BETWEEN 1 AND 1000);

ALTER TABLE ghm.business
  ADD CONSTRAINT business_directory_review_event_type_check
  CHECK (directory_review_last_event_type IS NULL OR directory_review_last_event_type IN ('submitted','resubmitted','approved','rejected','information_requested'));

CREATE TABLE ghm.directory_listing_founder_reviewer (
  account_id bigint PRIMARY KEY REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  created_by_account_id bigint REFERENCES ghm.account_identity(id) ON DELETE RESTRICT,
  notes text
);
ALTER TABLE ghm.directory_listing_founder_reviewer OWNER TO ghm_schema_owner;
ALTER TABLE ghm.directory_listing_founder_reviewer ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE ghm.directory_listing_founder_reviewer FROM PUBLIC, ghm_runtime;

CREATE TABLE ghm.business_directory_review_event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id bigint NOT NULL REFERENCES ghm.business(id) ON DELETE RESTRICT,
  actor_account_id bigint REFERENCES ghm.account_identity(id) ON DELETE SET NULL,
  event_type text NOT NULL CHECK (event_type IN ('submitted','resubmitted','approved','rejected','information_requested')),
  from_status text CHECK (from_status IS NULL OR from_status IN ('unverified','under_review','information_requested','approved','rejected')),
  to_status text NOT NULL CHECK (to_status IN ('unverified','under_review','information_requested','approved','rejected')),
  reason text CHECK (reason IS NULL OR char_length(btrim(reason)) BETWEEN 1 AND 1000),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE ghm.business_directory_review_event OWNER TO ghm_schema_owner;
ALTER TABLE ghm.business_directory_review_event ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE ghm.business_directory_review_event FROM PUBLIC, ghm_runtime;
CREATE INDEX business_directory_review_event_business_idx
  ON ghm.business_directory_review_event (business_id, created_at DESC, id DESC);
CREATE INDEX business_directory_review_event_queue_idx
  ON ghm.business_directory_review_event (event_type, created_at, id);

CREATE OR REPLACE FUNCTION ghm.is_directory_listing_founder_reviewer(p_account_id bigint)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
  SELECT p_account_id IS NOT NULL AND EXISTS (
    SELECT 1 FROM ghm.directory_listing_founder_reviewer r WHERE r.account_id = p_account_id
  );
$$;
ALTER FUNCTION ghm.is_directory_listing_founder_reviewer(bigint) OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.is_directory_listing_founder_reviewer(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ghm.is_directory_listing_founder_reviewer(bigint) TO ghm_runtime;

CREATE OR REPLACE FUNCTION ghm.submit_business_directory_review(p_account_id bigint, p_business_id bigint)
RETURNS TABLE (business_id bigint, verification_status text, is_verified boolean, directory_review_submitted_at timestamptz, directory_review_last_reason text, directory_review_last_event_type text)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
DECLARE
  v_business ghm.business%ROWTYPE;
  v_event text;
  v_owner_count integer;
BEGIN
  IF p_account_id IS NULL OR p_account_id <= 0 OR p_business_id IS NULL OR p_business_id <= 0 THEN
    RAISE EXCEPTION 'Directory review request is invalid';
  END IF;
  SELECT * INTO v_business FROM ghm.business b WHERE b.id = p_business_id AND b.is_active = true FOR UPDATE;
  IF NOT FOUND OR NOT EXISTS (
    SELECT 1 FROM ghm.business_membership bm
    WHERE bm.business_id = p_business_id AND bm.account_id = p_account_id
      AND bm.membership_status = 'active' AND bm.membership_role IN ('owner','administrator')
  ) THEN
    RAISE EXCEPTION 'Business management permission required';
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM ghm.business_registration_identity ri
    WHERE ri.business_id = p_business_id AND ri.registration_status IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'Business registration declaration is required before directory review';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM ghm.directory_listing_founder_reviewer) THEN
    RAISE EXCEPTION 'Founder directory reviewer authority is not configured';
  END IF;
  IF v_business.verification_status = 'under_review' THEN
    RETURN QUERY SELECT v_business.id, v_business.verification_status, v_business.is_verified,
      v_business.directory_review_submitted_at, v_business.directory_review_last_reason, v_business.directory_review_last_event_type;
    RETURN;
  END IF;
  IF v_business.verification_status NOT IN ('unverified','rejected','information_requested') THEN
    RAISE EXCEPTION 'Business cannot be submitted for directory review from status %', v_business.verification_status;
  END IF;
  v_event := CASE WHEN v_business.verification_status IN ('rejected','information_requested') THEN 'resubmitted' ELSE 'submitted' END;
  UPDATE ghm.business SET verification_status='under_review', is_verified=false,
    directory_review_submitted_at=clock_timestamp(), directory_review_last_reason=NULL,
    directory_review_last_event_type=v_event, updated_at=clock_timestamp()
    WHERE id=p_business_id RETURNING * INTO v_business;
  INSERT INTO ghm.business_directory_review_event (business_id,actor_account_id,event_type,from_status,to_status,metadata)
    VALUES (p_business_id,p_account_id,v_event,
      CASE WHEN v_event='submitted' THEN 'unverified' ELSE (SELECT verification_status FROM ghm.business WHERE id=p_business_id) END,
      'under_review',jsonb_build_object('version',1));
  FOR v_owner_count IN SELECT r.account_id FROM ghm.directory_listing_founder_reviewer r LOOP
    INSERT INTO ghm.notification (user_id,type,title,body,metadata)
      VALUES (v_owner_count,'verification',
        CASE WHEN v_event='resubmitted' THEN 'Directory listing resubmitted' ELSE 'Directory listing awaiting review' END,
        v_business.name || CASE WHEN v_event='resubmitted' THEN ' was resubmitted for directory review.' ELSE ' is awaiting directory review.' END,
        jsonb_build_object('businessId',p_business_id,'event',v_event,'verificationStatus','under_review'));
  END LOOP;
  RETURN QUERY SELECT v_business.id, v_business.verification_status, v_business.is_verified,
    v_business.directory_review_submitted_at, v_business.directory_review_last_reason, v_business.directory_review_last_event_type;
END;
$$;
ALTER FUNCTION ghm.submit_business_directory_review(bigint,bigint) OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.submit_business_directory_review(bigint,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ghm.submit_business_directory_review(bigint,bigint) TO ghm_runtime;

CREATE OR REPLACE FUNCTION ghm.list_businesses_for_directory_review(
  p_account_id bigint, p_status text DEFAULT 'under_review', p_limit integer DEFAULT 20, p_offset integer DEFAULT 0
)
RETURNS TABLE (
  id bigint, name text, slug text, description text, phone text, email text,
  verification_status text, is_verified boolean, is_active boolean,
  directory_review_submitted_at timestamptz, directory_review_last_reason text,
  directory_review_last_event_type text, owner_account_id bigint, owner_full_name text,
  registration_status text, registration_number text, legal_name text, created_at timestamptz
)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
BEGIN
  IF NOT ghm.is_directory_listing_founder_reviewer(p_account_id) THEN
    RAISE EXCEPTION 'Founder directory review authority required';
  END IF;
  IF p_limit IS NULL OR p_limit < 1 OR p_limit > 100 OR p_offset IS NULL OR p_offset < 0 THEN
    RAISE EXCEPTION 'Directory review pagination is invalid';
  END IF;
  IF p_status IS NOT NULL AND p_status NOT IN ('under_review','information_requested','rejected','approved','unverified') THEN
    RAISE EXCEPTION 'Directory review status filter is invalid';
  END IF;
  RETURN QUERY
    SELECT b.id,b.name,b.slug,b.description,b.phone,b.email,b.verification_status,b.is_verified,b.is_active,
      b.directory_review_submitted_at,b.directory_review_last_reason,b.directory_review_last_event_type,
      owner_membership.account_id,owner_account.full_name,ri.registration_status,ri.registration_number,ri.legal_name,b.created_at
    FROM ghm.business b
    LEFT JOIN LATERAL (
      SELECT bm.account_id FROM ghm.business_membership bm
      WHERE bm.business_id=b.id AND bm.membership_status='active' AND bm.membership_role='owner'
      ORDER BY bm.created_at,bm.id LIMIT 1
    ) owner_membership ON true
    LEFT JOIN ghm.account_identity owner_account ON owner_account.id=owner_membership.account_id
    LEFT JOIN ghm.business_registration_identity ri ON ri.business_id=b.id
    WHERE (p_status IS NULL OR b.verification_status=p_status)
      AND b.directory_review_submitted_at IS NOT NULL
    ORDER BY b.directory_review_submitted_at ASC NULLS LAST,b.created_at ASC,b.id ASC
    LIMIT p_limit OFFSET p_offset;
END;
$$;
ALTER FUNCTION ghm.list_businesses_for_directory_review(bigint,text,integer,integer) OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.list_businesses_for_directory_review(bigint,text,integer,integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ghm.list_businesses_for_directory_review(bigint,text,integer,integer) TO ghm_runtime;

CREATE OR REPLACE FUNCTION ghm.review_business_directory_listing(
  p_account_id bigint,p_business_id bigint,p_decision text,p_reason text DEFAULT NULL
)
RETURNS TABLE (business_id bigint,verification_status text,is_verified boolean,directory_review_last_reason text,directory_review_last_event_type text)
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
DECLARE
  v_business ghm.business%ROWTYPE;
  v_reason text := NULLIF(btrim(p_reason),'');
  v_next_status text;
  v_event text;
  v_owner_id bigint;
BEGIN
  IF NOT ghm.is_directory_listing_founder_reviewer(p_account_id) THEN
    RAISE EXCEPTION 'Founder directory review authority required';
  END IF;
  IF p_business_id IS NULL OR p_business_id <= 0 THEN RAISE EXCEPTION 'Business identifier is invalid'; END IF;
  IF p_decision NOT IN ('approve','reject','request_information') THEN RAISE EXCEPTION 'Directory review decision is invalid'; END IF;
  IF p_decision IN ('reject','request_information') AND (v_reason IS NULL OR char_length(v_reason)>1000) THEN
    RAISE EXCEPTION 'A reason between 1 and 1000 characters is required';
  END IF;
  SELECT * INTO v_business FROM ghm.business b WHERE b.id=p_business_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Business not found'; END IF;
  IF v_business.verification_status IS DISTINCT FROM 'under_review' THEN RAISE EXCEPTION 'Only businesses under review can be decided'; END IF;
  v_next_status := CASE p_decision WHEN 'approve' THEN 'approved' WHEN 'reject' THEN 'rejected' ELSE 'information_requested' END;
  v_event := v_next_status;
  UPDATE ghm.business SET verification_status=v_next_status,is_verified=(p_decision='approve'),
    directory_review_last_reason=CASE WHEN p_decision='approve' THEN NULL ELSE v_reason END,
    directory_review_last_event_type=v_event,updated_at=clock_timestamp()
    WHERE id=p_business_id RETURNING * INTO v_business;
  INSERT INTO ghm.business_directory_review_event (business_id,actor_account_id,event_type,from_status,to_status,reason,metadata)
    VALUES (p_business_id,p_account_id,v_event,'under_review',v_next_status,
      CASE WHEN p_decision='approve' THEN NULL ELSE v_reason END,
      jsonb_build_object('version',1,'decision',p_decision));
  SELECT bm.account_id INTO v_owner_id FROM ghm.business_membership bm
    WHERE bm.business_id=p_business_id AND bm.membership_status='active' AND bm.membership_role='owner'
    ORDER BY bm.created_at,bm.id LIMIT 1;
  IF v_owner_id IS NOT NULL THEN
    INSERT INTO ghm.notification (user_id,type,title,body,metadata)
    VALUES (v_owner_id,'verification',
      CASE p_decision WHEN 'approve' THEN 'Directory listing approved' WHEN 'reject' THEN 'Directory listing not approved' ELSE 'More information required' END,
      CASE p_decision
        WHEN 'approve' THEN v_business.name || ' has been approved for the public directory while active.'
        WHEN 'reject' THEN v_business.name || ' was not approved. Reason: ' || v_reason
        ELSE 'Action required for ' || v_business.name || ': ' || v_reason END,
      jsonb_build_object('businessId',p_business_id,'event',v_event,'verificationStatus',v_next_status));
  END IF;
  RETURN QUERY SELECT v_business.id,v_business.verification_status,v_business.is_verified,
    v_business.directory_review_last_reason,v_business.directory_review_last_event_type;
END;
$$;
ALTER FUNCTION ghm.review_business_directory_listing(bigint,bigint,text,text) OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.review_business_directory_listing(bigint,bigint,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ghm.review_business_directory_listing(bigint,bigint,text,text) TO ghm_runtime;

CREATE OR REPLACE FUNCTION ghm.get_business_directory_review_presentation(p_account_id bigint,p_business_id bigint)
RETURNS TABLE (business_id bigint,verification_status text,is_verified boolean,directory_review_submitted_at timestamptz,directory_review_last_reason text,directory_review_last_event_type text)
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $$
BEGIN
  IF p_account_id IS NULL OR p_business_id IS NULL OR p_business_id <= 0 OR NOT EXISTS (
    SELECT 1 FROM ghm.business_membership bm JOIN ghm.business b ON b.id=bm.business_id
    WHERE bm.business_id=p_business_id AND bm.account_id=p_account_id AND bm.membership_status='active'
      AND bm.membership_role IN ('owner','administrator') AND b.is_active=true
  ) THEN
    RAISE EXCEPTION 'Business management permission required';
  END IF;
  RETURN QUERY SELECT b.id,b.verification_status,b.is_verified,b.directory_review_submitted_at,
    b.directory_review_last_reason,b.directory_review_last_event_type
    FROM ghm.business b WHERE b.id=p_business_id;
END;
$$;
ALTER FUNCTION ghm.get_business_directory_review_presentation(bigint,bigint) OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.get_business_directory_review_presentation(bigint,bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION ghm.get_business_directory_review_presentation(bigint,bigint) TO ghm_runtime;
