-- Explicit external account mapping for controlled Connect data migration.
-- Separate from business_external_mapping; no email matching or auth-token acceptance.
-- This lookup is migrator-only and is not an authentication mechanism.

CREATE TABLE ghm.account_external_mapping (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider text NOT NULL,
  external_account_id text NOT NULL,
  account_id bigint NOT NULL
    REFERENCES ghm.account_identity(id)
    ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),

  CONSTRAINT account_external_mapping_provider_external_unique
    UNIQUE (provider, external_account_id),
  CONSTRAINT account_external_mapping_provider_nonblank_check
    CHECK (btrim(provider) <> ''),
  CONSTRAINT account_external_mapping_external_id_nonblank_check
    CHECK (btrim(external_account_id) <> '')
);

CREATE INDEX account_external_mapping_account_provider_idx
  ON ghm.account_external_mapping (account_id, provider);

COMMENT ON TABLE ghm.account_external_mapping IS
  'Explicit provider-scoped external account identifier to canonical GHM account mapping for controlled migration. Never inferred from email and never a credential or authorization grant.';

ALTER TABLE ghm.account_external_mapping OWNER TO ghm_schema_owner;

REVOKE ALL ON TABLE ghm.account_external_mapping
  FROM PUBLIC, ghm_runtime, ghm_migrator;

CREATE OR REPLACE FUNCTION ghm.auth_lookup_account_external_mapping(
  p_provider text,
  p_external_account_id text
)
RETURNS TABLE (account_id bigint)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, ghm
AS $function$
  SELECT mapping.account_id
    FROM ghm.account_external_mapping AS mapping
   WHERE p_provider IS NOT NULL
     AND btrim(p_provider) <> ''
     AND p_external_account_id IS NOT NULL
     AND btrim(p_external_account_id) <> ''
     AND mapping.provider = btrim(p_provider)
     AND mapping.external_account_id = btrim(p_external_account_id)
   LIMIT 2;
$function$;

ALTER FUNCTION ghm.auth_lookup_account_external_mapping(text, text)
  OWNER TO ghm_schema_owner;
REVOKE ALL ON FUNCTION ghm.auth_lookup_account_external_mapping(text, text)
  FROM PUBLIC, ghm_runtime;
GRANT EXECUTE ON FUNCTION ghm.auth_lookup_account_external_mapping(text, text)
  TO ghm_migrator;

COMMENT ON FUNCTION ghm.auth_lookup_account_external_mapping(text, text) IS
  'Migration-only lookup from an explicitly linked external account identifier to a canonical GHM account ID. Not an auth endpoint; does not validate external credentials, auto-link, or grant authorization.';
