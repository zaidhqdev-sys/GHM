import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import test from 'node:test';

const migration=readFileSync('database/migrations/20261120010000_add_signed_business_capability_create.sql','utf8');
const table=readFileSync('database/migrations/20260916210000_create_business_capability.sql','utf8');
const narrowed=readFileSync('database/migrations/20260916213000_narrow_business_capability_runtime_insert.sql','utf8');
const signedVerifier=readFileSync('database/migrations/20261111070000_add_signed_business_capability_mutations.sql','utf8');

test('signed create migration targets the canonical append-only Business Capability relation',()=>{
 assert.match(table,/id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
 assert.match(table,/CONSTRAINT business_capability_unique\s+UNIQUE \(business_id, capability_id\)/);
 assert.match(narrowed,/GRANT INSERT \([\s\S]*effective_from,[\s\S]*effective_until,[\s\S]*created_by/);
 assert.match(migration,/INSERT INTO ghm\.business_capability[\s\S]*RETURNING \*/);
 assert.doesNotMatch(migration,/ON CONFLICT/i);
 assert.doesNotMatch(migration,/UPDATE\s+ghm\.business_capability/i);
 assert.doesNotMatch(migration,/DELETE\s+FROM\s+ghm\.business_capability/i);
});

test('signed create binds the exact payload and uses the existing create assertion operation',()=>{
 assert.match(signedVerifier,/'business\.capability\.create'/);
 assert.match(migration,/p_context::jsonb\s*<>\s*p_payload/);
 assert.match(migration,/ghm\.assert_actor_gateway_capability\(\s*p_actor,\s*'business\.capability\.create'/);
 assert.match(migration,/p_payload\s*-\s*ARRAY\[/);
 assert.match(migration,/RETURNING \*/);
});

test('signed create enforces business authority and selectable active catalogue state in SQL',()=>{
 assert.match(migration,/FROM ghm\.business b[\s\S]*b\.is_active = true[\s\S]*FOR UPDATE/);
 assert.match(migration,/FROM ghm\.business_membership bm[\s\S]*bm\.membership_status = 'active'[\s\S]*FOR SHARE/);
 assert.match(migration,/v_membership_role NOT IN \('owner','administrator'\)/);
 assert.match(migration,/FROM ghm\.capability c[\s\S]*c\.lifecycle_status = 'active'[\s\S]*c\.is_selectable = true/);
});

test('signed create derives lifecycle, verification and actor provenance server-side',()=>{
 assert.match(migration,/'active',\s*'self_declared',\s*'unverified'/);
 assert.match(migration,/v_source_reference, transaction_timestamp\(\), v_actor/);
 assert.match(migration,/v_effective_from := COALESCE\(v_effective_from, transaction_timestamp\(\)\)/);
 assert.doesNotMatch(migration,/p_payload\s*->>\s*'createdBy'/);
 assert.doesNotMatch(migration,/p_payload\s*->>\s*'verificationStatus'/);
 assert.doesNotMatch(migration,/p_payload\s*->>\s*'assertionStatus'/);
});

test('signed create function is restricted to Actor Gateway execution',()=>{
 const signature='gateway_create_business_capability(bigint,bigint,uuid,text,text,jsonb)';
 assert.ok(migration.includes('ALTER FUNCTION ghm.'+signature+' OWNER TO ghm_schema_owner'));
 assert.ok(migration.includes('REVOKE ALL ON FUNCTION ghm.'+signature+' FROM PUBLIC, ghm_runtime, ghm_migrator'));
 assert.ok(migration.includes('GRANT EXECUTE ON FUNCTION ghm.'+signature+' TO ghm_actor_gateway'));
 assert.doesNotMatch(migration,/GRANT\s+(?:INSERT|USAGE)[\s\S]*TO\s+ghm_runtime/i);
});
